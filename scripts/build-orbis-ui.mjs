const setVar = (text, name, value) => {
  const re = new RegExp(`(--${name.replace(/[-]/g, '\\-')}:)[^;]*;`)
  if (!re.test(text)) throw new Error('cr_shared_vars.css: no --' + name)
  return text.replace(re, `$1 ${value};`)
}
