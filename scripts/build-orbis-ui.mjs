const hex = (n) => n.toString(16).toUpperCase().padStart(2, '0')
function argb(s) {
  s = s.trim()
  let m = /^#([0-9a-f]{6})$/i.exec(s)
  if (m) return '0xFF' + m[1].toUpperCase()
  m = /^rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+)\s*)?\)$/i.exec(s)
  if (m) return '0x' + hex(Math.round((m[4] === undefined ? 1 : +m[4]) * 255)) + hex(+m[1]) + hex(+m[2]) + hex(+m[3])
  return null
}
const camel = (k) => 'k' + k.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join('')
const px = (s) => parseInt(s, 10)
let h = `// GENERATED by scripts/build-orbis-ui.mjs from orbis-ui/tokens.json - do not edit.
// The one source of colours, radii and type sizes for the Orbis browser UI (Views). Synced to ui/color/orbis_tokens.h.
#ifndef UI_COLOR_ORBIS_TOKENS_H_
#define UI_COLOR_ORBIS_TOKENS_H_

#include <cstdint>

namespace orbis {

// Colours are 0xAARRGGBB (the same layout as SkColor).
`
for (const scheme of ['dark', 'light']) {
  h += `namespace ${scheme} {\n`
  for (const [k, v] of Object.entries(t[scheme])) { const c = argb(v); if (c) h += `constexpr uint32_t ${camel(k)} = ${c};\n` }
  h += `}  // namespace ${scheme}\n\n`
}
h += `// Sizes in DIPs.\nnamespace size {\n`
for (const [k, v] of Object.entries(t.scale.radius)) h += `constexpr int kRadius${camel(k).slice(1)} = ${k === 'pill' ? 999 : px(v)};\n`
for (const [k, v] of Object.entries(t.scale.text)) h += `constexpr int kText${camel(k).slice(1)} = ${px(v)};\n`
for (const [k, v] of Object.entries(t.scale.space)) h += `constexpr int kSpace${k} = ${px(v)};\n`
// The geometry of the browser chrome itself — tab pill, hit targets, the omnibox. These live in tokens.json
// alongside the colours so the Views browser and the web surfaces are shaped by one source and cannot drift apart.
h += `// Chrome geometry, from tokens.json scale.chrome.
`
for (const [k, v] of Object.entries(t.scale.chrome)) h += `constexpr int k${camel(k).slice(1)} = ${px(v)};
`
h += `constexpr int kMotionFastMs = ${px(t.scale.motion.fast)};
}  // namespace size

// Font: first family of the token stack that ships with Windows (the Views UI cannot load web fonts).
constexpr char kFontFamily[] = "Segoe UI";
// The address bar sets a URL in the mono face, as the Electron browser does. Consolas rather than the first
// family of the token stack: it is the one in that stack Windows is guaranteed to have, and Views cannot fall
// back through a web font list.
constexpr char kFontMono[] = "Consolas";

}  // namespace orbis

#endif  // UI_COLOR_ORBIS_TOKENS_H_
`
mkdirSync(new URL('../orbis-ui/generated/', import.meta.url), { recursive: true })
writeFileSync(new URL('../orbis-ui/generated/orbis_tokens.h', import.meta.url), h)
console.log('wrote orbis-tokens.css and generated/orbis_tokens.h')

// ---- Shared WebUI style foundation (synced into ui/webui/resources by scripts/sync-orbis-panel.ps1) ----
// orbis-ui/stock/cr_shared_vars.css is Chromium 154.0.8037.44's file, unmodified. Every colour, radius, spacing and shadow that Orbis
// changes is written here from tokens.json, so the tokens stay the only place a value lives.
const rgbOf = (s) => {
  s = s.trim()
  let m = /^#([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i.exec(s)
  if (m) return [parseInt(m[1], 16), parseInt(m[2], 16), parseInt(m[3], 16)]
  m = /^rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)/i.exec(s)
  return m ? [+m[1], +m[2], +m[3]] : null
}
const mix = (a, b, w) => a.map((v, i) => Math.round(v * (1 - w) + b[i] * w)) // w = share of b
const trip = (c) => c.join(', ')
const over = (fg, bg) => { const m = /rgba\(\s*[\d.]+\s*,\s*[\d.]+\s*,\s*[\d.]+\s*,\s*([\d.]+)\)/.exec(fg); const a = m ? +m[1] : 1; return mix(rgbOf(bg), rgbOf(fg), a) }
const WHITE = [255, 255, 255], BLACK = [0, 0, 0]
let crvars = readFileSync(new URL('../orbis-ui/stock/cr_shared_vars.css', import.meta.url), 'utf8').replace(/\r\n/g, '\n')
const setVar = (text, name, value) => {
  const re = new RegExp(`(--${name.replace(/[-]/g, '\\-')}:)[^;]*;`)
  if (!re.test(text)) throw new Error('cr_shared_vars.css: no --' + name)
  return text.replace(re, `$1 ${value};`)
}
const aL = rgbOf(t.light.accent), aD = rgbOf(t.dark.accent)
const ramp = { 50: mix(aL, WHITE, 0.9), 100: mix(aL, WHITE, 0.8), 200: mix(aL, WHITE, 0.55), 300: aD, 400: mix(aD, BLACK, 0.12), 500: aL, 600: aL, 700: mix(aL, BLACK, 0.2), 800: mix(aL, BLACK, 0.37), 900: mix(aL, BLACK, 0.5) }
for (const [k, c] of Object.entries(ramp)) crvars = setVar(crvars, `google-blue-${k}-rgb`, trip(c))
const sp = t.scale.space, rad = t.scale.radius
crvars = setVar(crvars, 'cr-card-border-radius', rad.md)
crvars = setVar(crvars, 'cr-button-edge-spacing', sp['3'])
crvars = setVar(crvars, 'cr-section-vertical-padding', sp['3'])
crvars = setVar(crvars, 'cr-section-padding', `${px(sp['4']) + 4}px`)
crvars = setVar(crvars, 'cr-menu-shadow', t.light.shadow)
crvars = setVar(crvars, 'cr-card-shadow', `0 0 0 1px ${t.light.line}`)
