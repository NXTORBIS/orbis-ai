// Generates from orbis-ui/tokens.json (the single token source):
//   orbis-ui/orbis-tokens.css                        WebUI CSS variables
//   orbis-ui/generated/orbis_tokens.h                C++ constexpr values for Chromium's Views UI (synced to ui/color/orbis_tokens.h)
//   src/renderer/src/styles/tokens.generated.css      the same variables for the Orbis window (Electron renderer)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
const t = JSON.parse(readFileSync(new URL('../orbis-ui/tokens.json', import.meta.url), 'utf8'))
const vars = (o, p) => Object.entries(o).map(([k, v]) => `  --${p}${k}: ${v};`).join('\n')
const flat = (o, p = '') => Object.entries(o).flatMap(([k, v]) => typeof v === 'object' ? flat(v, `${p}${k}-`) : [`  --${p}${k}: ${v};`]).join('\n')
// `color-scheme` belongs with the palette, not with the features.
//
// It is what tells Windows which way to paint the parts of a control it draws itself: the list a <select> drops
// down, a scrollbar, a date picker. It was being set per feature -- `select { color-scheme: dark }` with a
// `:root[data-theme='light']` override beside it -- and that override only fires for the FORCED light theme. On a
// machine set to light with Orbis following the system, the window went light and every drop-down list stayed
// black. Written here it lands in all four palette blocks at once, so the scheme can never disagree with the
// colours it is meant to go with.
const scheme = (name) => `  color-scheme: ${name};`
const css = `/* GENERATED by scripts/build-orbis-ui.mjs from tokens.json - do not edit */
:root {\n${flat({ font: t.font, ...t.scale })}\n${vars(t.dark, '')}\n${scheme('dark')}\n}
@media (prefers-color-scheme: light) { :root:not([data-theme='dark']) {\n${vars(t.light, '')}\n${scheme('light')}\n} }
:root[data-theme='light'] {\n${vars(t.light, '')}\n${scheme('light')}\n}
`
writeFileSync(new URL('../orbis-ui/orbis-tokens.css', import.meta.url), css)

// ---- The Orbis window (Electron renderer) ----
// The window used to hand-write its own palette at the top of src/renderer/src/styles.css, with different names for
// the same colours (--cyan for the accent, --glass-border for the hairline, --font for the type face). A colour had
// to be changed in two places, and the copy that reached Chromium's own window frame was the one in tokens.json, so
// the two drifted. The window now reads the same tokens as the browser pages.
//
// The old names are kept alive as aliases pointing at the token they always meant. That is what makes this a small
// change: the twenty thousand lines of stylesheet underneath keep saying var(--cyan) and keep working. A name comes
// off the list when the CSS for one feature is moved over to the token name -- per feature, as that CSS is touched,
// not in one pass.
const LEGACY = {
  font: 'font-sans',
  display: 'font-display',
  mono: 'font-mono',
  cyan: 'accent',
  'cyan-dim': 'accent-dim',
  'cyan-fill': 'accent-fill',
  'cyan-glow': 'accent-glow',
  'cyan-glow-soft': 'accent-glow-soft',
  'glass-shadow': 'shadow',
  // These three were never declared anywhere: the window asked for them and CSS fell back to a hard-coded colour
  // that ignored the theme (a near-black media backdrop in light mode), or, for --panel, to nothing at all, so four
  // panels drew no background. They are the same three surfaces the tokens already name.
  panel: 'surface-2',
  'bg-deep': 'bg',
  'bg-hover': 'hover'
}
const aliases = Object.entries(LEGACY).map(([from, to]) => `  --${from}: var(--${to});`).join('\n')
const appCss = `/* GENERATED by scripts/build-orbis-ui.mjs from orbis-ui/tokens.json - do not edit */
/* Imported before styles.css by src/renderer/src/main.tsx. */
:root {\n${flat({ font: t.font, ...t.scale })}\n${vars(t.dark, '')}\n${scheme('dark')}\n}
@media (prefers-color-scheme: light) { :root:not([data-theme='dark']) {\n${vars(t.light, '')}\n${scheme('light')}\n} }
:root[data-theme='light'] {\n${vars(t.light, '')}\n${scheme('light')}\n}
:root[data-theme='dark'] {\n${vars(t.dark, '')}\n${scheme('dark')}\n}

/* DEPRECATED. The window's old names, each one pointing at the token it means. Nothing new should use these. */
:root {\n${aliases}\n}
`
mkdirSync(new URL('../src/renderer/src/styles/', import.meta.url), { recursive: true })
writeFileSync(new URL('../src/renderer/src/styles/tokens.generated.css', import.meta.url), appCss)

