function coefficientRows(fit: ArimaFit): CoefRow[] {
  const estimates = [...fit.phi, ...fit.theta, ...(fit.includeMean ? [fit.mean] : [])];
  return fit.parameterNames.map((name, i) => ({
    name,
    estimate: estimates[i] ?? NaN,
    se: fit.standardErrors ? (fit.standardErrors[i] ?? null) : null,
  }));
}

function forecastRows(point: number[], innovation: TsInterval[], parameter: TsInterval[] | null, innovationSd: number[]): ForecastRow[] {
  return point.map((p, i) => ({
    h: i + 1,
    point: p,
    innovationSd: innovationSd[i] ?? NaN,
    innovation: innovation[i],
    parameter: parameter ? (parameter[i] ?? null) : null,
  }));
}

/** Chart points from a component that may be undefined at some positions. */
function definedPoints(values: (number | null)[]): { x: number; y: number }[] {
  const out: { x: number; y: number }[] = [];
  for (let i = 0; i < values.length; i++) {
    const v = values[i];
    if (v !== null && Number.isFinite(v)) out.push({ x: i + 1, y: v });
  }
  return out;
}

/** A test result rendered exactly as the engine reports it, brackets included. */
function TestResultView({ result }: { result: TsTestResult }) {
  return (
    <div className="oc-stack">
      <KeyValueList
        items={[
          { label: 'Test', value: result.name },
          { label: 'Statistic', value: formatValue(result.statistic, 6) },
          { label: 'Degrees of freedom', value: result.df === null ? 'not applicable' : formatValue(result.df, 4) },
          {
            label: 'p-value',
            // Never a fabricated precise number: when the engine has only a
            // table, it reports a bracket and the bracket is what is shown.
            value: result.pValue !== null ? formatValue(result.pValue, 5) : (result.pValueBracket ?? 'not available'),
          },
          { label: 'Null hypothesis', value: result.nullHypothesis },
          { label: 'Alternative', value: result.alternative },
          { label: 'Exactness', value: <Badge variant={result.explanation.exactness}>{EXACTNESS_LABEL[result.explanation.exactness]}</Badge> },
        ]}
      />
      {result.pValue !== null && result.pValueBracket && <p className="oc-chart-note">{result.pValueBracket}</p>}
      <p style={{ fontSize: 12.5, margin: 0 }}>{result.interpretation}</p>
      {result.criticalValues && result.criticalValues.length > 0 && (
        <div style={{ overflowX: 'auto' }}>
          <DataTable
            caption={`Tabulated critical values for ${result.name}`}
            columns={[
              { key: 'l', header: 'Significance level', numeric: true, render: (r: CriticalValueRow) => formatValue(r.level, 3) },
              { key: 'v', header: 'Critical value', numeric: true, render: (r: CriticalValueRow) => formatValue(r.value, 5) },
              {
                key: 'r',
                header: 'Rejected at this level',
                render: (r: CriticalValueRow) => {
                  const hit = result.rejectAt?.find((x) => x.level === r.level);
                  return hit ? (hit.reject ? 'yes' : 'no') : 'not reported';
                },
              },
            ]}
            rows={result.criticalValues}
          />
        </div>
      )}
      <ExplanationPanel explanation={result.explanation} />
    </div>
  );
}

/** The engine's own warnings, never paraphrased and never hidden. */
function WarningList({ warnings }: { warnings: string[] }) {
  if (!warnings.length) return null;
  return <Notice tone="warning" title={warnings.length === 1 ? 'One caveat from the engine' : `${warnings.length} caveats from the engine`} items={warnings} />;
}
