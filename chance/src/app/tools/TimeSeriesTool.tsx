/**
 * Built-in series: 144 monthly observations with a linear trend, a twelve-period
 * seasonal shape and an AR(1) innovation, generated by a fixed linear
 * congruential sequence so the figures are identical on every machine. It is
 * synthetic demonstration data and the interface says so wherever it is used.
 */
const BUILT_IN_SERIES: number[] = (() => {
  let state = 20250917;
  const uniform = (): number => {
    state = (state * 1103515245 + 12345) % 2147483648;
    return state / 2147483648;
  };
  const out: number[] = [];
  let noise = 0;
  for (let t = 0; t < 144; t++) {
    const trend = 120 + 0.65 * t;
    const seasonal = 14 * Math.sin((2 * Math.PI * t) / 12) + 6 * Math.cos((4 * Math.PI * t) / 12);
    // Irwin–Hall(12) is an adequate approximately-normal innovation here, and
    // the AR(1) carry-forward is what makes the effective sample size
    // interesting rather than equal to n.
    let u = 0;
    for (let k = 0; k < 12; k++) u += uniform();
    noise = 0.55 * noise + 3 * (u - 6);
    out.push(Math.round((trend + seasonal + noise) * 100) / 100);
  }
  return out;
})();

