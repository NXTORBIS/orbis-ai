/* ----------------------------------------------------------------- parsing */

interface ParsedData {
  x: number[];
  y: number[];
  lineErrors: { line: number; reason: string }[];
}

/**
 * Pasted data is untrusted. Every line is checked and anything unreadable is
 * reported with its line number rather than dropped: a silent drop changes n,
 * and n is in every standard error on this screen.
 */
function parseData(text: string): ParsedData {
  const x: number[] = [];
  const y: number[] = [];
  const lineErrors: ParsedData['lineErrors'] = [];
  text.split(/\r?\n/).forEach((raw, i) => {
    const line = raw.trim();
    if (!line || line.startsWith('#')) return;
    const tokens = line.split(/[,;\s]+/).filter(Boolean);
    if (tokens.length !== 2) {
      lineErrors.push({ line: i + 1, reason: `expected exactly two numbers (x and y), found ${tokens.length}` });
      return;
    }
    const a = Number(tokens[0]);
    const b = Number(tokens[1]);
    if (!Number.isFinite(a) || !Number.isFinite(b)) {
      lineErrors.push({ line: i + 1, reason: `"${line.slice(0, 40)}" is not a pair of finite numbers` });
      return;
    }
    x.push(a);
    y.push(b);
  });
  return { x, y, lineErrors };
}

/* ------------------------------------------------- the model set being compared */

/** Design row for a degree-d polynomial: 1, x, x², …, x^d. */
function designRow(x: number, degree: number): number[] {
  const row = new Array<number>(degree + 1);
  let p = 1;
  for (let j = 0; j <= degree; j++) {
    row[j] = p;
    p *= x;
  }
  return row;
}

interface PolyFit {
  degree: number;
  /** Coefficients, lowest power first. */
  beta: number[];
  /** Maximum-likelihood error variance, RSS/n. */
  sigmaSquared: number;
  /** Gaussian log-likelihood at the maximum. */
  logLikelihood: number;
  /** Coefficients plus the variance: every estimated quantity counted. */
  parameters: number;
  n: number;
  fitted: number[];
}

/**
 * Least squares by the normal equations, with the Gaussian log-likelihood at
 * the maximum:
 *   sigma^2 = RSS/n,  lnL = −n/2 · (ln 2π + ln sigma^2 + 1).
 * The variance is counted as an estimated parameter, so k = d + 2. Dropping
 * it would make the information criteria of different degrees incomparable.
 *
 * `solve` returns null for a singular system, which is what a high-degree
 * polynomial on few points produces. That is reported, never patched.
 */
function fitPolynomial(x: readonly number[], y: readonly number[], degree: number): PolyFit {
  const n = x.length;
  const p = degree + 1;
  if (n <= p) {
    throw new EngineError(
      `A degree-${degree} polynomial has ${p} coefficients and there are ${n} observations. With n ≤ p the residual variance is zero or undefined and no likelihood exists.`,
      'insufficient',
    );
  }
  const xtx: number[][] = Array.from({ length: p }, () => new Array<number>(p).fill(0));
  const xty = new Array<number>(p).fill(0);
  for (let i = 0; i < n; i++) {
    const row = designRow(x[i], degree);
    for (let a = 0; a < p; a++) {
      xty[a] += row[a] * y[i];
      for (let b = 0; b < p; b++) xtx[a][b] += row[a] * row[b];
    }
  }
  const beta = solve(xtx, xty);
  if (!beta) {
    throw new EngineError(
      `The degree-${degree} design matrix is numerically singular on this data, so the least-squares coefficients do not exist. The raw powers are too strongly correlated at this degree; drop it from the model set or use fewer powers.`,
      'degenerate',
    );
  }
  const fitted = new Array<number>(n);
  let rss = 0;
  for (let i = 0; i < n; i++) {
    const row = designRow(x[i], degree);
    let f = 0;
    for (let a = 0; a < p; a++) f += row[a] * beta[a];
    fitted[i] = f;
    rss += (y[i] - f) * (y[i] - f);
  }
  const sigmaSquared = rss / n;
  if (!(sigmaSquared > 0) || !Number.isFinite(sigmaSquared)) {
    throw new EngineError(
      `The degree-${degree} fit has a residual variance of ${String(sigmaSquared)}, so its Gaussian log-likelihood is not finite and it cannot be compared with the others.`,
      'nonfinite',
    );
  }
  const logLikelihood = (-n / 2) * (Math.log(2 * Math.PI) + Math.log(sigmaSquared) + 1);
  return { degree, beta, sigmaSquared, logLikelihood, parameters: degree + 2, n, fitted };
}

const MODEL_NAME = (degree: number): string => `Degree ${degree}`;

/** Normal log density, used for the held-out predictive density and the likelihood. */
function normalLogPdf(value: number, mean: number, variance: number): number {
  return -0.5 * (Math.log(2 * Math.PI * variance) + ((value - mean) * (value - mean)) / variance);
}

/* -------------------------------------------------- the known-variance g-prior */

/**
 * The model used for the evidence section, and the only model on this screen
 * with a marginal likelihood at all:
 *   y | beta ~ Normal(X·beta, sigma^2·I) with sigma KNOWN,
 *   beta     ~ Normal(0, sigma^2·g·I),  g the prior scale.
 * Then, integrating beta out exactly,
 *   y ~ Normal(0, sigma^2·(I + g·X·Xᵀ)),
 * which is the closed form `analyticEvidence` is given below, and
 *   beta | y ~ Normal( C⁻¹Xᵀy, sigma^2·C⁻¹ ),  C = XᵀX + I/g,
 * which is the posterior the Monte Carlo estimate and DIC are built from.
 * Both numbers are then shown side by side: the estimate has no business
 * disagreeing with the closed form by more than its own standard error.
 */
interface GPriorPosterior {
  degree: number;
  mean: number[];
  /** Cholesky factor L of C = XᵀX + I/g, lower triangular. */
  cholC: number[][];
  logEvidence: number;
}

function gPriorFit(
  x: readonly number[],
  y: readonly number[],
  degree: number,
  sigma: number,
  g: number,
): GPriorPosterior {
  const n = x.length;
  const p = degree + 1;
  if (!(sigma > 0) || !Number.isFinite(sigma)) {
    throw new EngineError(`The known error standard deviation must be a positive finite number; got ${String(sigma)}.`, 'range');
  }
  if (!(g > 0) || !Number.isFinite(g)) {
    throw new EngineError(`The prior scale g must be a positive finite number; got ${String(g)}.`, 'range');
  }
  const variance = sigma * sigma;
  const X: number[][] = [];
  for (let i = 0; i < n; i++) X.push(designRow(x[i], degree));

  // C = XᵀX + I/g, and the posterior mean C⁻¹Xᵀy.
  const C: number[][] = Array.from({ length: p }, () => new Array<number>(p).fill(0));
  const xty = new Array<number>(p).fill(0);
  for (let i = 0; i < n; i++) {
    for (let a = 0; a < p; a++) {
      xty[a] += X[i][a] * y[i];
      for (let b = 0; b < p; b++) C[a][b] += X[i][a] * X[i][b];
    }
  }
  for (let a = 0; a < p; a++) C[a][a] += 1 / g;
  const mean = solve(C, xty);
  const chol = choleskyWithCheck(C);
  if (!mean || !chol.ok) {
    throw new EngineError(
      `The degree-${degree} posterior precision matrix is not numerically positive definite, so neither the posterior nor the marginal likelihood can be formed at this prior scale. Reduce the degree or the prior scale g.`,
      'degenerate',
    );
  }

  // log p(y) = −n/2·ln(2π·sigma²) − ½·ln|M| − yᵀM⁻¹y/(2·sigma²), M = I + g·XXᵀ.
  // |M| and M⁻¹y are obtained from the p×p matrices rather than an n×n
  // inverse: |I + g·XXᵀ| = |I + g·XᵀX| = g^p·|C|, and
  // M⁻¹ = I − X(XᵀX + I/g)⁻¹Xᵀ, both standard identities.
  let logDetC = 0;
  for (let a = 0; a < p; a++) logDetC += 2 * Math.log(chol.L[a][a]);
  const logDetM = p * Math.log(g) + logDetC;
  const cinvXty = solve(C, xty);
  if (!cinvXty) {
    throw new EngineError(`The degree-${degree} marginal likelihood could not be formed: the linear system C·z = Xᵀy has no solution.`, 'degenerate');
  }
  let yty = 0;
  for (let i = 0; i < n; i++) yty += y[i] * y[i];
  let quadratic = yty;
  for (let a = 0; a < p; a++) quadratic -= xty[a] * cinvXty[a];
  const logEvidence = (-n / 2) * Math.log(2 * Math.PI * variance) - 0.5 * logDetM - quadratic / (2 * variance);
  if (!Number.isFinite(logEvidence)) {
    throw new EngineError(
      `The degree-${degree} log marginal likelihood evaluated to ${String(logEvidence)}. It is not reported as a number because it is not one.`,
      'nonfinite',
    );
  }
  return { degree, mean, cholC: chol.L, logEvidence };
}

/** Solve Lᵀ·w = z by back substitution; with z ~ N(0, I) this gives w ~ N(0, C⁻¹). */
function backSolveTranspose(L: readonly (readonly number[])[], z: readonly number[]): number[] {
  const p = z.length;
  const w = new Array<number>(p).fill(0);
  for (let i = p - 1; i >= 0; i--) {
    let acc = z[i];
    for (let j = i + 1; j < p; j++) acc -= L[j][i] * w[j];
    w[i] = acc / L[i][i];
  }
  return w;
}

/** Exact draws from beta | y, and the log-likelihood at each of them. */
function posteriorDraws(
  post: GPriorPosterior,
  x: readonly number[],
  y: readonly number[],
  sigma: number,
  count: number,
  seed: string,
): { draws: number[][]; logLikDraws: number[] } {
  const rng = new Random(seed);
  const p = post.mean.length;
  const variance = sigma * sigma;
  const draws: number[][] = [];
  const logLikDraws: number[] = [];
  const design = x.map((xi) => designRow(xi, post.degree));
  for (let s = 0; s < count; s++) {
    const z = new Array<number>(p);
    for (let a = 0; a < p; a++) z[a] = rng.normal();
    const w = backSolveTranspose(post.cholC, z);
    const beta = new Array<number>(p);
    for (let a = 0; a < p; a++) beta[a] = post.mean[a] + sigma * w[a];
    let ll = 0;
    for (let i = 0; i < design.length; i++) {
      let f = 0;
      for (let a = 0; a < p; a++) f += design[i][a] * beta[a];
      ll += normalLogPdf(y[i], f, variance);
    }
    draws.push(beta);
    logLikDraws.push(ll);
  }
  return { draws, logLikDraws };
}

/* ----------------------------------------------------------------- helpers */

type Attempt<T> = { ok: true; value: T } | { ok: false; error: string };

/** EngineError messages are surfaced exactly as the engine wrote them. */
function attempt<T>(run: () => T): Attempt<T> {
  try {
    return { ok: true, value: run() };
  } catch (e) {
    return { ok: false, error: e instanceof EngineError ? e.message : e instanceof Error ? e.message : String(e) };
  }
}

function num(value: number | null | undefined, digits = 5): string {
  if (value === null || value === undefined || !Number.isFinite(value)) return 'not available';
  return formatValue(value, digits);
}

