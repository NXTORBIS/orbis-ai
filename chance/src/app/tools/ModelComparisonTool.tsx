/**
 * Ranges for the knobs that drive a refit count or a draw count. A
 * `NumberField` reports whatever was typed and shows its own out-of-range
 * message beside the field, but it does not clamp, so a typed "1e9" would
 * otherwise reach the estimator and freeze the tab. The fold count's upper
 * limit depends on the data, so it is passed in.
 */
function withinRange(value: number, min: number, max: number): number {
  if (!Number.isFinite(value)) return min;
  return Math.min(max, Math.max(min, Math.round(value)));
}

export function ModelComparisonTool({ config }: { config: ModelComparisonConfig }) {
  const app = useApp();
  const set = (patch: Partial<ModelComparisonConfig>) => app.updateConfig({ ...config, ...patch });

  const evidenceDraws = withinRange(config.evidenceDraws, 100, 20_000);

  // Which model's own criteria are shown in detail. A view preference only:
  // it changes nothing that is computed, so it does not belong in the config.
  const [detailDegree, setDetailDegree] = useState<number | null>(null);

  const parsed = useMemo(() => parseData(config.dataText), [config.dataText]);

  // Refit- and draw-driving knobs, read through their declared range. The
  // fields show the out-of-range message; this keeps the estimators from
  // being handed the typed value, and `outOfRange` says what was used.
  const folds = withinRange(config.folds, 2, Math.max(2, parsed.x.length));
  const outOfRange = [
    ...(evidenceDraws === config.evidenceDraws
      ? []
      : [`“Posterior draws per model” is ${String(config.evidenceDraws)}, outside its range 100–20,000. The evidence estimates used ${evidenceDraws.toLocaleString('en-US')}.`]),
    ...(folds === config.folds || config.cvMode === 'loo'
      ? []
      : [`“Folds” is ${String(config.folds)}, outside its range 2–${Math.max(2, parsed.x.length)}. Cross-validation used ${folds.toLocaleString('en-US')}.`]),
  ];
  const degrees = useMemo(() => [...new Set(config.degrees)].sort((a, b) => a - b), [config.degrees]);

  /** The model set: one maximum-likelihood fit per degree, each able to fail alone. */
  const fits = useMemo(
    () => degrees.map((degree) => ({ degree, fit: attempt(() => fitPolynomial(parsed.x, parsed.y, degree)) })),
    [degrees, parsed.x, parsed.y],
  );
  const usable = useMemo(
    () => fits.flatMap((f) => (f.fit.ok ? [{ degree: f.degree, value: f.fit.value }] : [])),
    [fits],
  );

  /** AIC, AICc and BIC per model: exact arithmetic on the likelihoods above. */
  const criteria = useMemo(
    () =>
      usable.map((m) => ({
        degree: m.degree,
        result: attempt(() =>
          informationCriteria({
            name: MODEL_NAME(m.degree),
            logLikelihood: m.value.logLikelihood,
            parameters: m.value.parameters,
            observations: m.value.n,
          }),
        ),
      })),
    [usable],
  );

  /** The ranking and its relative likelihoods, from the engine. */
  const ranking = useMemo(
    () =>
      attempt(() =>
        criterionWeights(
          usable.map((m) => ({
            name: MODEL_NAME(m.degree),
            logLikelihood: m.value.logLikelihood,
            parameters: m.value.parameters,
            observations: m.value.n,
          })),
          config.criterion,
        ),
      ),
    [usable, config.criterion],
  );

  /** Averaging by the criterion weights, which is a heuristic and is labelled as one. */
  const criterionAveraging = useMemo(
    () =>
      ranking.ok
        ? attempt(() =>
            bayesianModelAverage({
              names: ranking.value.weights.map((w) => w.name),
              weights: ranking.value.weights.map((w) => w.weight),
              source: 'akaike',
            }),
          )
        : null,
    [ranking],
  );

  /* --------------------------------------------------------- cross-validation */

  /**
   * Cross-validation, behind `runCrossValidation`. The fold refit is plain
   * least squares on the training indices; the held-out density is the
   * plug-in Normal predictive at the training fit, which is stated in the
   * interface because it ignores parameter uncertainty.
   */
  const crossValidated = useMemo(() => {
    if (!config.runCrossValidation) return null;
    return usable.map((m) => ({
      degree: m.degree,
      result: attempt<CrossValidationResult>(() => {
        const fold = (train: readonly number[], test: readonly number[]): number[] => {
          const trainX = train.map((i) => parsed.x[i]);
          const trainY = train.map((i) => parsed.y[i]);
          const f = fitPolynomial(trainX, trainY, m.degree);
          return test.map((i) => {
            const row = designRow(parsed.x[i], m.degree);
            let mu = 0;
            for (let a = 0; a < row.length; a++) mu += row[a] * f.beta[a];
            return normalLogPdf(parsed.y[i], mu, f.sigmaSquared);
          });
        };
        return config.cvMode === 'loo'
          ? exactLeaveOneOut(MODEL_NAME(m.degree), parsed.x.length, fold)
          : kFoldCrossValidation(MODEL_NAME(m.degree), parsed.x.length, folds, fold, {
              seed: config.cvSeed,
              shuffle: true,
            });
      }),
    }));
  }, [config.runCrossValidation, config.cvMode, folds, config.cvSeed, usable, parsed.x, parsed.y]);

  const elpdEstimates = useMemo(
    () => (crossValidated ?? []).flatMap((c) => (c.result.ok ? [c.result.value] : [])),
    [crossValidated],
  );

  const comparison = useMemo(
    () => (elpdEstimates.length > 0 ? attempt(() => compareElpd(elpdEstimates)) : null),
    [elpdEstimates],
  );

  /** One named pair, so the difference and its standard error stand alone. */
  const pairDifference = useMemo(() => {
    const [a, b] = config.differencePair;
    const left = elpdEstimates.find((e) => e.name === MODEL_NAME(a));
    const right = elpdEstimates.find((e) => e.name === MODEL_NAME(b));
    if (!left || !right) return null;
    return attempt(() => elpdDifference(left, right));
  }, [elpdEstimates, config.differencePair]);

  const stacking = useMemo(
    () => (elpdEstimates.length > 1 ? attempt<ModelWeights>(() => stackingWeights(elpdEstimates)) : null),
    [elpdEstimates],
  );

  const pseudoBma = useMemo(
    () =>
      elpdEstimates.length > 1
        ? attempt<ModelWeights>(() =>
            pseudoBmaWeights(elpdEstimates, { bayesianBootstrap: true, replicates: 1000, seed: `${config.cvSeed}:bb` }),
          )
        : null,
    [elpdEstimates, config.cvSeed],
  );

  /* ---------------------------------------------------------------- evidence */

  /**
   * Evidence, behind `runEvidence`: the closed-form marginal likelihood, the
   * bridge-sampling estimate of the same quantity from exact posterior draws,
   * and DIC from those draws. Each model is attempted on its own.
   */
  const evidence = useMemo(() => {
    if (!config.runEvidence) return null;
    return usable.map((m) => {
      const computed = attempt(() => {
        const post = gPriorFit(parsed.x, parsed.y, m.degree, config.evidenceSigma, config.priorScale);
        const exact: EvidenceEstimate = analyticEvidence(MODEL_NAME(m.degree), post.logEvidence);
        const { draws, logLikDraws } = posteriorDraws(
          post,
          parsed.x,
          parsed.y,
          config.evidenceSigma,
          evidenceDraws,
          `${config.evidenceSeed}:d${m.degree}`,
        );
        const variance = config.evidenceSigma * config.evidenceSigma;
        const priorVariance = variance * config.priorScale;
        const design = parsed.x.map((xi) => designRow(xi, m.degree));
        const logJoint = (beta: readonly number[]): number => {
          let total = 0;
          for (let a = 0; a < beta.length; a++) total += normalLogPdf(beta[a], 0, priorVariance);
          for (let i = 0; i < design.length; i++) {
            let mu = 0;
            for (let a = 0; a < beta.length; a++) mu += design[i][a] * beta[a];
            total += normalLogPdf(parsed.y[i], mu, variance);
          }
          return total;
        };
        const estimated = estimateEvidence(MODEL_NAME(m.degree), draws, logJoint, `${config.evidenceSeed}:bridge${m.degree}`, {
          method: config.evidenceMethod,
        });
        // The log-likelihood at the posterior mean, so DIC uses the plug-in
        // effective parameter count rather than the variance-based one.
        const atMean = (() => {
          let ll = 0;
          for (let i = 0; i < design.length; i++) {
            let mu = 0;
            for (let a = 0; a < post.mean.length; a++) mu += design[i][a] * post.mean[a];
            ll += normalLogPdf(parsed.y[i], mu, variance);
          }
          return ll;
        })();
        const dicResult = dic({ name: MODEL_NAME(m.degree), logLikDraws, logLikAtPosteriorMean: atMean });
        return { exact, estimated, dic: dicResult };
      });
      return { degree: m.degree, computed };
    });
  }, [
    config.runEvidence,
    config.evidenceSigma,
    config.priorScale,
    evidenceDraws,
    config.evidenceMethod,
    config.evidenceSeed,
    usable,
    parsed.x,
    parsed.y,
  ]);

  const bayesFactorResult = useMemo(() => {
    if (!evidence) return null;
    const [numeratorDegree, denominatorDegree] = config.bayesFactorPair;
    const numerator = evidence.find((e) => e.degree === numeratorDegree);
    const denominator = evidence.find((e) => e.degree === denominatorDegree);
    const left = numerator?.computed;
    const right = denominator?.computed;
    if (!left?.ok || !right?.ok) return null;
    if (numeratorDegree === denominatorDegree) {
      return { ok: false as const, error: 'A Bayes factor compares two different models. Choose two different degrees.' };
    }
    return attempt(() => bayesFactor(left.value.exact, right.value.exact));
  }, [evidence, config.bayesFactorPair]);

  /* ------------------------------------------------------------------ charts */

  /** Chart inputs, computed here; the chart components only draw them. */
  const weightBars = useMemo(
    () => (ranking.ok ? ranking.value.weights.map((w, i) => ({ x: usable[i]?.degree ?? i, y: w.weight, label: w.name })) : []),
    [ranking, usable],
  );

  const stackingBars = useMemo(
    () =>
      stacking?.ok
        ? stacking.value.names.map((name, k) => ({ x: Number(name.replace(/\D+/g, '')), y: stacking.value.weights[k], label: name }))
        : [],
    [stacking],
  );

  const fitCurves = useMemo(() => {
    if (usable.length === 0 || parsed.x.length === 0) return [];
    const lo = Math.min(...parsed.x);
    const hi = Math.max(...parsed.x);
    const grid = Array.from({ length: 120 }, (_, i) => lo + ((hi - lo) * i) / 119);
    return [
      { label: 'Observations', points: parsed.x.map((xi, i) => ({ x: xi, y: parsed.y[i] })).sort((a, b) => a.x - b.x), dashed: true },
      ...usable.map((m) => ({
        label: MODEL_NAME(m.degree),
        points: grid.map((gx) => {
          const row = designRow(gx, m.degree);
          let f = 0;
          for (let a = 0; a < row.length; a++) f += row[a] * m.value.beta[a];
          return { x: gx, y: f };
        }),
      })),
    ];
  }, [usable, parsed.x, parsed.y]);

  const elpdCurve = useMemo(
    () =>
      elpdEstimates.length > 0
        ? [
            {
              label: 'elpd',
              points: elpdEstimates
                .map((e) => ({ x: Number(e.name.replace(/\D+/g, '')), y: e.elpd }))
                .sort((a, b) => a.x - b.x),
            },
            {
              label: 'elpd − 1 standard error',
              dashed: true,
              points: elpdEstimates
                .map((e) => ({ x: Number(e.name.replace(/\D+/g, '')), y: e.elpd - e.standardError }))
                .sort((a, b) => a.x - b.x),
            },
            {
              label: 'elpd + 1 standard error',
              dashed: true,
              points: elpdEstimates
                .map((e) => ({ x: Number(e.name.replace(/\D+/g, '')), y: e.elpd + e.standardError }))
                .sort((a, b) => a.x - b.x),
            },
          ]
        : [],
    [elpdEstimates],
  );

  /* ----------------------------------------------------------------- columns */

  const criterionColumns: ColumnDef<{ degree: number; value: CriterionValue; delta: number; weight: number; evidenceRatio: number }>[] = [
    { key: 'm', header: 'Model', render: (r) => r.value.name },
    { key: 'k', header: 'k', numeric: true, title: 'Estimated parameters, the error variance included.', render: (r) => r.value.parameters },
    { key: 'll', header: 'ln L', numeric: true, render: (r) => num(r.value.logLikelihood, 6) },
    { key: 'aic', header: 'AIC', numeric: true, render: (r) => num(r.value.aic, 6) },
    { key: 'aicc', header: 'AICc', numeric: true, render: (r) => (r.value.aicc === null ? 'undefined (n − k − 1 ≤ 0)' : num(r.value.aicc, 6)) },
    { key: 'bic', header: 'BIC', numeric: true, render: (r) => num(r.value.bic, 6) },
    { key: 'd', header: `Δ${config.criterion.toUpperCase()}`, numeric: true, render: (r) => num(r.delta, 4) },
    { key: 'w', header: 'Weight', numeric: true, title: 'Relative likelihood of being the best model in this set by this criterion. Not a probability of truth.', render: (r) => num(r.weight, 4) },
    { key: 'er', header: 'Evidence ratio', numeric: true, render: (r) => (Number.isFinite(r.evidenceRatio) ? num(r.evidenceRatio, 4) : 'beyond floating point') },
    {
      key: 'pick',
      header: 'Detail',
      render: (r) => (
        <Button size="sm" variant="ghost" disabled={detailDegree === r.degree} onClick={() => setDetailDegree(r.degree)}>
          Show
        </Button>
      ),
    },
  ];

  const criterionRows = useMemo(() => {
    if (!ranking.ok) return [];
    return ranking.value.values.map((value, i) => ({
      degree: usable[i]?.degree ?? i,
      value,
      delta: ranking.value.weights[i].delta,
      weight: ranking.value.weights[i].weight,
      evidenceRatio: ranking.value.weights[i].evidenceRatio,
    }));
  }, [ranking, usable]);

  const elpdColumns: ColumnDef<(typeof elpdEstimates)[number]>[] = [
    { key: 'm', header: 'Model', render: (r) => r.name },
    { key: 'e', header: 'elpd', numeric: true, title: 'Expected log pointwise predictive density. Higher is better.', render: (r) => num(r.elpd, 6) },
    { key: 'se', header: '± standard error', numeric: true, render: (r) => num(r.standardError, 4) },
    { key: 'ic', header: 'IC (−2·elpd)', numeric: true, render: (r) => num(r.informationCriterion, 6) },
    { key: 'f', header: 'Method', render: (r) => (r.method === 'exact-loo' ? 'exact leave-one-out' : `${r.method}`) },
    { key: 'x', header: 'Exactness', render: (r) => <Badge variant={r.exactness}>{EXACTNESS_LABEL[r.exactness]}</Badge> },
  ];

  const differenceColumns: ColumnDef<ElpdDifference>[] = [
    { key: 'p', header: 'Pair', render: (r) => `${r.better} − ${r.worse}` },
    { key: 'd', header: 'Δelpd', numeric: true, render: (r) => num(r.difference, 5) },
    { key: 'se', header: 'Standard error (paired)', numeric: true, render: (r) => num(r.standardError, 5) },
    { key: 'n', header: 'Naive independent se', numeric: true, title: 'What the standard error would be if the two models made independent errors. They do not; this column is shown for contrast and must not be used.', render: (r) => num(r.naiveStandardError, 5) },
    { key: 'z', header: 'Δ / se', numeric: true, render: (r) => (Number.isFinite(r.zScore) ? num(r.zScore, 3) : 'standard error is zero') },
    { key: 'v', header: 'Verdict', render: (r) => VERDICT_WORD[r.verdict] },
  ];

  const weightsColumns: ColumnDef<{ name: string; weight: number }>[] = [
    { key: 'm', header: 'Model', render: (r) => r.name },
    { key: 'w', header: 'Weight', numeric: true, render: (r) => num(r.weight, 5) },
  ];

  const evidenceColumns: ColumnDef<{
    degree: number;
    closed: number | null;
    estimated: number | null;
    logSe: number | null;
    dicValue: number | null;
    effective: number | null;
    error: string | null;
  }>[] = [
    { key: 'm', header: 'Model', render: (r) => MODEL_NAME(r.degree) },
    { key: 'c', header: 'log evidence (closed form)', numeric: true, render: (r) => (r.error ? '—' : num(r.closed, 7)) },
    { key: 'e', header: 'log evidence (estimated)', numeric: true, render: (r) => (r.error ? '—' : num(r.estimated, 7)) },
    { key: 's', header: '± log se of the estimate', numeric: true, render: (r) => (r.error ? '—' : num(r.logSe, 4)) },
    { key: 'd', header: 'DIC', numeric: true, render: (r) => (r.error ? '—' : num(r.dicValue, 6)) },
    { key: 'p', header: 'pD', numeric: true, title: 'Effective number of parameters, plug-in definition.', render: (r) => (r.error ? '—' : num(r.effective, 4)) },
    { key: 'x', header: 'Status', render: (r) => r.error ?? 'computed' },
  ];

  const evidenceRows = useMemo(
    () =>
      (evidence ?? []).map((e) => ({
        degree: e.degree,
        closed: e.computed.ok ? e.computed.value.exact.logMarginalLikelihood : null,
        estimated: e.computed.ok ? e.computed.value.estimated.logMarginalLikelihood : null,
        logSe: e.computed.ok ? e.computed.value.estimated.logStandardError : null,
        dicValue: e.computed.ok ? e.computed.value.dic.dic : null,
        effective: e.computed.ok ? e.computed.value.dic.effectiveParameters : null,
        error: e.computed.ok ? null : e.computed.error,
      })),
    [evidence],
  );

  const detailFit = usable.find((m) => m.degree === detailDegree) ?? null;
  const detailCriterionResult = criteria.find((c) => c.degree === detailDegree)?.result ?? null;

  /** The engine's own Explanation for whichever section has produced one. */
  const criterionExplanation: Explanation | null = ranking.ok ? ranking.value.explanation : null;

  /* ------------------------------------------------------------------ render */

  return (
    <>
      <ToolHeader toolId="model-comparison" />
      <div className="oc-workspace">
        <div className="oc-stack">
          {outOfRange.length > 0 && <Notice tone="warning" title="A setting is outside the range its field allows" items={outOfRange} />}
          <Card title="Data">
            <TextField
              label="Observations, one x and y per line"
              value={config.dataText}
              onChange={(dataText) => set({ dataText })}
              multiline
              rows={12}
              monospace
              hint="Two numbers per line, separated by a space, comma or semicolon. Lines starting with # are ignored."
            />
            <div className="oc-btn-row">
              <Button size="sm" icon="data" onClick={() => set({ dataText: BUILT_IN_TEXT })}>
                Reload the built-in data
              </Button>
            </div>
            <p className="oc-chart-note">
              The built-in data is <strong>synthetic demonstration data, not measurements</strong>: 40 points generated by the fixed rule y = 1 + 2x − 0.5x² +
              0.3x³ + e with e ~ Normal(0, 1.2²), from a fixed linear congruential sequence so every machine sees the same numbers. The true model is the cubic,
              and the noise is large enough that the cubic, quartic and quintic cannot be separated — which is the case these standard errors exist for.
            </p>
            {parsed.lineErrors.length > 0 && (
              <Notice tone="warning" title={`${parsed.lineErrors.length} line(s) could not be read and are NOT included in n`}>
                <ul className="oc-assumption-list">
                  {parsed.lineErrors.slice(0, 10).map((e, i) => (
                    <li key={i}>
                      Line {e.line}: {e.reason}
                    </li>
                  ))}
                </ul>
                {parsed.lineErrors.length > 10 && <p>And {parsed.lineErrors.length - 10} more.</p>}
              </Notice>
            )}
            <KeyValueList
              items={[
                { label: 'n (pairs read)', value: parsed.x.length.toLocaleString('en-US') },
                { label: 'Lines rejected', value: parsed.lineErrors.length.toLocaleString('en-US') },
                { label: 'Models in the set', value: degrees.length.toLocaleString('en-US') },
              ]}
            />
          </Card>

          <Card title="The model set" hint="Nested polynomial regressions. Each added degree can only improve the in-sample fit.">
            {AVAILABLE_DEGREES.map((d) => (
              <Checkbox
                key={d}
                checked={degrees.includes(d)}
                onChange={(on) => set({ degrees: on ? [...degrees, d] : degrees.filter((v) => v !== d) })}
                label={`Degree ${d}`}
                description={`${d + 2} estimated parameters: ${d + 1} coefficients and the error variance.`}
              />
            ))}
            {degrees.length === 0 && (
              <Notice tone="warning" title="No models selected">
                Nothing can be compared until at least one degree is chosen, and at least two before any comparison means anything.
              </Notice>
            )}
            {fits.some((f) => !f.fit.ok) && (
              <Notice
                tone="error"
                title="Some models in the set could not be fitted"
                items={fits.flatMap((f) => (f.fit.ok ? [] : [f.fit.error]))}
              />
            )}
          </Card>

          <Card title="Criterion">
            <Segmented
              label="Information criterion used for the ranking"
              value={config.criterion}
              onChange={(criterion) => set({ criterion })}
              options={[
                { value: 'aic', label: 'AIC' },
                { value: 'aicc', label: 'AICc' },
                { value: 'bic', label: 'BIC' },
              ]}
            />
            <Notice tone="info" title="AIC and BIC are answering different questions">
              AIC estimates out-of-sample predictive loss; BIC approximates a marginal likelihood under a prior nobody chose, and asks about truth rather than
              prediction. Where they disagree, neither is wrong. A gap below about {NEGLIGIBLE_GAP} units is not a preference either way.
            </Notice>
          </Card>

          <AiAssistPanel
            capability="suggestMethod"
            context="Which models to compare is a modelling decision. The rankings, paired standard errors and weights on this screen are the evidence, and all of them come from the engine rather than from a language model."
          />
        </div>

        <div className="oc-stack">
          {/* ------------------------------------------- information criteria */}
          <Card
            title="Information criteria"
            hint="Exact arithmetic on the fitted log-likelihoods."
            actions={<Badge variant="exact">{EXACTNESS_LABEL.exact}</Badge>}
          >
            {!ranking.ok ? (
              <Notice tone="error" title="No ranking could be produced">
                {ranking.error}
              </Notice>
            ) : (
              <>
                <Notice tone={ranking.value.indistinguishable ? 'warning' : 'info'} title={ranking.value.indistinguishable ? 'The leading models cannot be separated' : `Lowest ${config.criterion.toUpperCase()}: ${ranking.value.best}`}>
                  <p style={{ margin: 0 }}>{ranking.value.statement}</p>
                </Notice>
                <div style={{ overflowX: 'auto' }}>
                  <DataTable caption="Information criteria and relative likelihoods per model" columns={criterionColumns} rows={criterionRows} />
                </div>
                <BarChart
                  title={`${config.criterion.toUpperCase()} weights`}
                  description={`Relative likelihood of each polynomial degree being the best model in this set by ${config.criterion.toUpperCase()}.`}
                  data={weightBars}
                  xLabel="Polynomial degree"
                  yLabel="Weight"
                  seriesLabel={`${config.criterion.toUpperCase()} weight`}
                  note="These weights are relative likelihoods within this set. They are not probabilities that a model is true, and they do not become them by summing to 1."
                />
                <Notice tone="info" title="What this ranking does and does not say" items={[...ranking.value.warnings]} />
                {criterionExplanation && <ExplanationPanel explanation={criterionExplanation} />}
              </>
            )}
          </Card>

          {detailFit && (
            <Card title={`Detail: ${MODEL_NAME(detailFit.degree)}`} actions={<Button size="sm" variant="ghost" onClick={() => setDetailDegree(null)}>Hide</Button>}>
              <KeyValueList
                items={[
                  { label: 'Observations', value: detailFit.value.n.toLocaleString('en-US') },
                  { label: 'Estimated parameters (coefficients + variance)', value: String(detailFit.value.parameters) },
                  { label: 'Log-likelihood at the maximum', value: num(detailFit.value.logLikelihood, 8) },
                  { label: 'Maximum-likelihood error variance', value: num(detailFit.value.sigmaSquared, 6) },
                  { label: 'AIC', value: criterionText(detailCriterionResult, (v) => num(v.aic, 7)) },
                  {
                    label: 'AICc',
                    value: criterionText(detailCriterionResult, (v) =>
                      v.aicc === null ? 'undefined: n − k − 1 ≤ 0 at this parameter count' : num(v.aicc, 7),
                    ),
                  },
                  { label: 'BIC', value: criterionText(detailCriterionResult, (v) => num(v.bic, 7)) },
                ]}
              />
              <p className="oc-chart-note">
                The coefficients of a raw-power polynomial are nearly uninterpretable on their own — the powers are strongly correlated — so the fitted curve
                below is the thing to judge, not the individual numbers.
              </p>
            </Card>
          )}

          <Card title="The fitted models" hint="Each curve is one member of the set being compared.">
            {fitCurves.length > 0 ? (
              <LineChart
                title="Data and fitted polynomials"
                description="The observations, with the fitted curve of each polynomial degree in the model set."
                series={fitCurves}
                xLabel="x"
                yLabel="y"
                note="Higher degrees follow the data more closely by construction. That is why in-sample fit cannot choose between them, and why everything below is out-of-sample."
              />
            ) : (
              <Notice tone="info">There is nothing to draw until at least one model has been fitted.</Notice>
            )}
          </Card>

          {/* ------------------------------------------- cross-validation */}
          <Card title="Out-of-sample comparison: cross-validation" hint="elpd with the standard error of every difference.">
            <Segmented
              label="Scheme"
              value={config.cvMode}
              onChange={(cvMode) => set({ cvMode })}
              options={[
                { value: 'loo', label: 'Exact leave-one-out' },
                { value: 'k-fold', label: 'Shuffled k-fold' },
              ]}
            />
            {config.cvMode === 'k-fold' && (
              <>
                <NumberField
                  label="Folds"
                  value={config.folds}
                  onChange={(folds) => set({ folds })}
                  min={2}
                  max={Math.max(2, parsed.x.length)}
                  integer
                  hint="Fewer folds means each model is fitted to less data, so k-fold is pessimistic about a model fitted to everything."
                />
                <TextField label="Fold-assignment seed" value={config.cvSeed} onChange={(cvSeed) => set({ cvSeed })} monospace hint="The engine refuses a shuffled assignment without a seed, so the folds are part of the record." />
              </>
            )}
            {!config.runCrossValidation ? (
              <>
                <Notice tone="info" title="Cross-validation is not run automatically">
                  <p style={{ marginTop: 0 }}>
                    Every model in the set is refitted once per fold. With {degrees.length} model(s) and{' '}
                    {config.cvMode === 'loo' ? parsed.x.length : folds} fold(s) that is{' '}
                    {degrees.length * (config.cvMode === 'loo' ? parsed.x.length : folds)} refits, which on a
                    larger dataset or a wider model set takes long enough to make the page unresponsive. It runs only when you ask for it.
                  </p>
                  <p style={{ marginBottom: 0 }}>
                    Until then nothing on this screen is out-of-sample, and the information criteria above are the only comparison available.
                  </p>
                </Notice>
                <div className="oc-btn-row">
                  <Button icon="play" variant="primary" disabled={usable.length === 0} onClick={() => set({ runCrossValidation: true })}>
                    Run cross-validation
                  </Button>
                </div>
                {usable.length === 0 && <p className="oc-muted">No model has been fitted, so there is nothing to cross-validate.</p>}
              </>
            ) : (
              <>
                <div className="oc-btn-row">
                  <Button size="sm" icon="x" onClick={() => set({ runCrossValidation: false })}>
                    Stop running cross-validation
                  </Button>
                </div>
                {(crossValidated ?? []).some((c) => !c.result.ok) && (
                  <Notice
                    tone="error"
                    title="Some models could not be cross-validated"
                    items={(crossValidated ?? []).flatMap((c) => (c.result.ok ? [] : [c.result.error]))}
                  />
                )}
                {elpdEstimates.length > 0 && (
                  <>
                    <div style={{ overflowX: 'auto' }}>
                      <DataTable caption="Out-of-sample predictive performance per model" columns={elpdColumns} rows={elpdEstimates} />
                    </div>
                    <p className="oc-chart-note">
                      The held-out density is the plug-in Normal predictive at the training fit, Normal(x·β̂, σ̂²) with both taken from the training data. It
                      therefore ignores uncertainty in β and σ², and is slightly optimistic about sharpness for that reason. The elpd standard error is the
                      spread of the pointwise terms over observations: it describes this estimate, not the model.
                    </p>
                    <LineChart
                      title="elpd by polynomial degree, with one standard error either side"
                      description="Estimated expected log pointwise predictive density per degree, with the band one standard error either side."
                      series={elpdCurve}
                      xLabel="Polynomial degree"
                      yLabel="elpd (higher is better)"
                      note="The band is the standard error of each model's own elpd, which is NOT the standard error of a difference between two of them. The differences, which are what a comparison needs, are in the table below."
                    />
                  </>
                )}
                {comparison && !comparison.ok && (
                  <Notice tone="error" title="The models could not be compared">
                    {comparison.error}
                  </Notice>
                )}
                {comparison?.ok && (
                  <>
                    <Notice
                      tone={comparison.value.verdict === 'clear' ? 'success' : comparison.value.verdict === 'weak' ? 'warning' : 'error'}
                      title={`${VERDICT_WORD[comparison.value.verdict]} — best elpd: ${comparison.value.best}`}
                    >
                      <p style={{ margin: 0 }}>{comparison.value.statement}</p>
                    </Notice>
                    {comparison.value.tiedWithBest.length > 0 && (
                      <Notice tone="warning" title="Models that cannot be separated from the best one">
                        <p style={{ marginTop: 0 }}>{comparison.value.tiedWithBest.join(', ')}</p>
                        <p style={{ marginBottom: 0 }}>
                          Their elpd difference from {comparison.value.best} is within {INDISTINGUISHABLE_Z} standard errors of the paired difference. Ranking
                          them against each other would be reading noise as a result, so this screen does not. Report them together, or average over them with
                          the stacking weights below.
                        </p>
                      </Notice>
                    )}
                    <div style={{ overflowX: 'auto' }}>
                      <DataTable
                        caption="Difference from the best model, paired"
                        columns={differenceColumns}
                        rows={[...comparison.value.differencesFromBest]}
                      />
                    </div>
                    <Disclosure title={`All ${comparison.value.allPairs.length} pairwise differences`} icon="table">
                      <div style={{ overflowX: 'auto' }}>
                        <DataTable caption="Every pairwise elpd difference with its paired standard error" columns={differenceColumns} rows={[...comparison.value.allPairs]} />
                      </div>
                      <p className="oc-chart-note">
                        These are many comparisons on the same data. Picking the most favourable of them is a selection effect, and nothing here corrects for
                        it.
                      </p>
                    </Disclosure>
                    <Notice tone="info" title="How to read a difference" items={[...comparison.value.warnings]} />
                    <ExplanationPanel explanation={comparison.value.explanation} />
                  </>
                )}

                {/* one named pair, on its own */}
                {elpdEstimates.length > 1 && (
                  <Card title="One pair on its own" variant="inset">
                    <div style={{ display: 'flex', gap: 'var(--s3)', flexWrap: 'wrap' }}>
                      <SelectField
                        label="First model"
                        value={String(config.differencePair[0])}
                        onChange={(v) => set({ differencePair: [Number(v), config.differencePair[1]] })}
                        options={degrees.map((d) => ({ value: String(d), label: MODEL_NAME(d) }))}
                      />
                      <SelectField
                        label="Second model"
                        value={String(config.differencePair[1])}
                        onChange={(v) => set({ differencePair: [config.differencePair[0], Number(v)] })}
                        options={degrees.map((d) => ({ value: String(d), label: MODEL_NAME(d) }))}
                      />
                    </div>
                    {!pairDifference && (
                      <Notice tone="info">
                        Both chosen models must have been cross-validated successfully before their paired difference can be computed.
                      </Notice>
                    )}
                    {pairDifference && !pairDifference.ok && <Notice tone="error">{pairDifference.error}</Notice>}
                    {pairDifference?.ok && (
                      <>
                        <Notice tone={VERDICT_TONE[pairDifference.value.verdict]} title={VERDICT_WORD[pairDifference.value.verdict]}>
                          <p style={{ margin: 0 }}>{pairDifference.value.statement}</p>
                        </Notice>
                        <KeyValueList
                          items={[
                            { label: 'Δelpd', value: `${num(pairDifference.value.difference, 6)} in favour of ${pairDifference.value.better}` },
                            { label: 'Standard error of the difference (paired)', value: num(pairDifference.value.standardError, 6) },
                            { label: 'Difference in standard errors', value: Number.isFinite(pairDifference.value.zScore) ? num(pairDifference.value.zScore, 3) : 'standard error is zero' },
                            { label: 'Naive independent standard error, for contrast', value: num(pairDifference.value.naiveStandardError, 6) },
                          ]}
                        />
                        <p className="oc-chart-note">
                          A difference smaller than its own standard error is not evidence of anything: with the same models and another sample of the same size
                          the sign could easily reverse. The paired standard error is the only correct one here, because two models fitted to the same
                          observations make correlated errors — the same hard points are hard for both.
                        </p>
                      </>
                    )}
                  </Card>
                )}

                {/* ---------------------------------------- model averaging */}
                <Card title="Model averaging" variant="inset">
                  <p style={{ fontSize: 12.5, marginTop: 0 }}>
                    Selecting one model and then reporting its uncertainty as though the selection had not happened understates that uncertainty, because the
                    choice was made with the same data. Where several models cannot be separated, the weighted mixture of their predictive distributions is
                    usually the better prediction and is the honest one.
                  </p>
                  {stacking && !stacking.ok && <Notice tone="error" title="Stacking weights could not be computed">{stacking.error}</Notice>}
                  {stacking?.ok && (
                    <>
                      <Notice tone="info" title="Stacking (optimises the mixture's leave-one-out log score)">
                        <p style={{ margin: 0 }}>{stacking.value.statement}</p>
                      </Notice>
                      <DataTable
                        caption="Stacking weights"
                        columns={weightsColumns}
                        rows={stacking.value.names.map((name, k) => ({ name, weight: stacking.value.weights[k] }))}
                      />
                      <KeyValueList
                        items={[
                          { label: 'Mean leave-one-out log score of the mixture', value: num(stacking.value.mixtureLogScore, 6) },
                          { label: 'Best single model, same score', value: num(stacking.value.bestSingleLogScore, 6) },
                          { label: 'Optimiser iterations', value: stacking.value.iterations.toLocaleString('en-US') },
                        ]}
                      />
                      <BarChart
                        title="Stacking weights"
                        description="Weight given to each polynomial degree by stacking of predictive distributions."
                        data={stackingBars}
                        xLabel="Polynomial degree"
                        yLabel="Weight"
                        seriesLabel="Stacking weight"
                        note="Stacking asks directly which mixture predicts best. It does not assume the true model is in the set — which it is not."
                      />
                      <ExplanationPanel explanation={stacking.value.explanation} />
                    </>
                  )}
                  {pseudoBma && !pseudoBma.ok && <Notice tone="error" title="Pseudo-BMA weights could not be computed">{pseudoBma.error}</Notice>}
                  {pseudoBma?.ok && (
                    <>
                      <Notice tone="info" title="Pseudo-BMA with the Bayesian bootstrap">
                        <p style={{ margin: 0 }}>{pseudoBma.value.statement}</p>
                      </Notice>
                      <DataTable
                        caption="Pseudo-BMA weights"
                        columns={weightsColumns}
                        rows={pseudoBma.value.names.map((name, k) => ({ name, weight: pseudoBma.value.weights[k] }))}
                      />
                      <Notice tone="warning" title="These are not posterior model probabilities" items={[...pseudoBma.value.warnings]} />
                    </>
                  )}
                  {criterionAveraging && !criterionAveraging.ok && (
                    <Notice tone="error" title="Averaging by criterion weights could not be computed">{criterionAveraging.error}</Notice>
                  )}
                  {criterionAveraging?.ok && (
                    <>
                      <Notice tone="warning" title="Averaging by criterion weights, for contrast">
                        <p style={{ margin: 0 }}>{criterionAveraging.value.statement}</p>
                      </Notice>
                      <Notice tone="info" items={[...criterionAveraging.value.warnings]} />
                    </>
                  )}
                </Card>
              </>
            )}
          </Card>

          {/* ------------------------------------------------- evidence */}
          <Card title="Bayesian evidence and Bayes factors" hint="A different question from prediction, with a different answer.">
            <Notice tone="warning" title="A Bayes factor is not a measure of predictive accuracy">
              It is a ratio of marginal likelihoods, each averaging the likelihood over the <strong>prior</strong>. The dependence on the prior does not wash out
              with more data: widening the prior on a parameter that only one model has drives the Bayes factor towards the other model without bound. Nothing in
              this section can be read without the prior that produced it, which is why the prior is an input below rather than a default hidden in the engine.
            </Notice>
            <NumberField
              label="Known error standard deviation σ"
              value={config.evidenceSigma}
              onChange={(evidenceSigma) => set({ evidenceSigma })}
              min={0.001}
              max={1000}
              step={0.1}
              hint="The evidence model treats σ as known. This is the only way the marginal likelihood here has a closed form to check the estimate against, and it is an assumption, not a result."
            />
            <NumberField
              label="Prior scale g"
              value={config.priorScale}
              onChange={(priorScale) => set({ priorScale })}
              min={0.01}
              max={10000}
              step={1}
              hint="Each coefficient has prior Normal(0, σ²·g). Increase it and watch every Bayes factor move towards the smaller model: that movement is the Jeffreys-Lindley paradox, not a change in the data."
            />
            {!config.runEvidence ? (
              <>
                <Notice tone="info" title="Evidence estimation is not run automatically">
                  <p style={{ marginTop: 0 }}>
                    Each model needs its posterior drawn ({evidenceDraws.toLocaleString('en-US')} draws) and then bridge sampling run over those draws, on
                    top of the closed-form value computed for comparison. Across {degrees.length} model(s) that is seconds of blocked main thread, so it runs only
                    when you ask for it.
                  </p>
                  <p style={{ marginBottom: 0 }}>
                    Both numbers are then shown together: a Monte Carlo estimate that disagrees with the closed form by more than its own standard error is a
                    broken estimate, and the point of showing them side by side is to be able to see that.
                  </p>
                </Notice>
                <div className="oc-btn-row">
                  <Button icon="play" variant="primary" disabled={usable.length === 0} onClick={() => set({ runEvidence: true })}>
                    Estimate the evidence
                  </Button>
                </div>
              </>
            ) : (
              <>
                <div className="oc-btn-row">
                  <Button size="sm" icon="x" onClick={() => set({ runEvidence: false })}>
                    Stop estimating the evidence
                  </Button>
                </div>
                <SelectField
                  label="Monte Carlo method"
                  value={config.evidenceMethod}
                  onChange={(evidenceMethod) => set({ evidenceMethod })}
                  options={[
                    { value: 'bridge-sampling', label: 'Bridge sampling' },
                    { value: 'importance-sampling', label: 'Importance sampling with a Gaussian proposal' },
                  ]}
                />
                <NumberField
                  label="Posterior draws per model"
                  value={config.evidenceDraws}
                  onChange={(evidenceDraws) => set({ evidenceDraws })}
                  min={100}
                  max={20000}
                  integer
                />
                <TextField label="Seed" value={config.evidenceSeed} onChange={(evidenceSeed) => set({ evidenceSeed })} monospace />
                <div style={{ overflowX: 'auto' }}>
                  <DataTable caption="Marginal likelihood, closed form against the Monte Carlo estimate, and DIC" columns={evidenceColumns} rows={evidenceRows} />
                </div>
                <p className="oc-chart-note">
                  The closed form is <strong>exact</strong> for this model: integrating a Normal prior against a Normal likelihood with known σ gives y ~
                  Normal(0, σ²(I + g·XXᵀ)). The estimated column is <strong>empirical</strong> and carries the Monte Carlo error beside it. DIC is reported for
                  continuity with older work only; it is not invariant to reparameterisation and is not recommended. Its warnings are listed below.
                </p>
                {(evidence ?? []).map((e) =>
                  e.computed.ok ? (
                    <Disclosure key={e.degree} title={`${MODEL_NAME(e.degree)}: evidence and DIC warnings`} icon="info">
                      <Notice tone="info" title="Evidence estimate" items={[...e.computed.value.estimated.warnings]} />
                      <Notice tone="warning" title="DIC" items={[...e.computed.value.dic.warnings]} />
                      <ExplanationPanel explanation={e.computed.value.dic.explanation} />
                    </Disclosure>
                  ) : null,
                )}
                <Card title="Bayes factor" variant="inset">
                  <div style={{ display: 'flex', gap: 'var(--s3)', flexWrap: 'wrap' }}>
                    <SelectField
                      label="Numerator model"
                      value={String(config.bayesFactorPair[0])}
                      onChange={(v) => set({ bayesFactorPair: [Number(v), config.bayesFactorPair[1]] })}
                      options={degrees.map((d) => ({ value: String(d), label: MODEL_NAME(d) }))}
                    />
                    <SelectField
                      label="Denominator model"
                      value={String(config.bayesFactorPair[1])}
                      onChange={(v) => set({ bayesFactorPair: [config.bayesFactorPair[0], Number(v)] })}
                      options={degrees.map((d) => ({ value: String(d), label: MODEL_NAME(d) }))}
                    />
                  </div>
                  {!bayesFactorResult && (
                    <Notice tone="info">Both chosen models need a computed evidence before their Bayes factor exists.</Notice>
                  )}
                  {bayesFactorResult && !bayesFactorResult.ok && <Notice tone="error">{bayesFactorResult.error}</Notice>}
                  {bayesFactorResult?.ok && (
                    <>
                      <Notice tone={bayesFactorResult.value.favours === 'neither' ? 'warning' : 'info'} title={bayesFactorResult.value.favours === 'neither' ? 'Not evidence for either model' : `Favours ${bayesFactorResult.value.favours}`}>
                        <p style={{ margin: 0 }}>{bayesFactorResult.value.statement}</p>
                      </Notice>
                      <KeyValueList
                        items={[
                          { label: 'Bayes factor', value: num(bayesFactorResult.value.bayesFactor, 6) },
                          { label: 'log Bayes factor', value: `${num(bayesFactorResult.value.logBayesFactor, 6)} ± ${num(bayesFactorResult.value.logStandardError, 4)}` },
                          { label: 'log₁₀ Bayes factor', value: num(bayesFactorResult.value.log10BayesFactor, 5) },
                          {
                            label: 'Jeffreys band (a convention, not a measurement)',
                            value: `${interpretBayesFactor(bayesFactorResult.value.log10BayesFactor)} — Jeffreys' conventional label for this log₁₀ value`,
                          },
                          { label: 'Exactness', value: <Badge variant={bayesFactorResult.value.exactness}>{EXACTNESS_LABEL[bayesFactorResult.value.exactness]}</Badge> },
                        ]}
                      />
                      <Notice tone="warning" title="The Jeffreys bands are a convention">
                        &ldquo;Substantial&rdquo;, &ldquo;strong&rdquo; and &ldquo;decisive&rdquo; are names Jeffreys attached to ranges of log₁₀ BF by
                        convention. They are not measurements, there is no theory that makes 3.16 the boundary of anything, and a Bayes factor on the wrong side
                        of a band boundary has not crossed a threshold in nature. Quote the number and the prior that produced it; the word is a label.
                      </Notice>
                      <Notice tone="info" items={[...bayesFactorResult.value.warnings]} />
                      <ExplanationPanel explanation={bayesFactorResult.value.explanation} />
                    </>
                  )}
                </Card>
              </>
            )}
          </Card>

          <Disclosure title="What this screen can and cannot tell you" icon="book">
            <p style={{ fontSize: 12.5 }}>
              Everything here ranks only the models supplied. None of them is likely to be true, and the best of a set of wrong models is still wrong: a
              comparison is silent about the model nobody fitted.
            </p>
            <p style={{ fontSize: 12.5 }}>
              The three families of answer on this screen are not interchangeable. Information criteria are cheap approximations to out-of-sample loss computed
              from an in-sample fit. Cross-validation estimates that loss directly, and is the one that reports the standard error of a difference, which is the
              only number that says whether a ranking is real. Marginal likelihoods and Bayes factors answer a question about the prior-averaged fit of each
              model, and keep depending on the prior however much data arrives.
            </p>
            <p style={{ fontSize: 12.5, margin: 0 }}>
              Where a difference is inside its own standard error, the correct report is that the data does not distinguish the models — not a ranking with a
              caveat attached. That is why this screen names the models tied with the best one, and offers the averaging weights rather than a winner.
            </p>
          </Disclosure>
        </div>
      </div>
    </>
  );
}
