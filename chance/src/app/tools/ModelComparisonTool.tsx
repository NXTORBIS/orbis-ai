/**
 * Model comparison and model averaging.
 *
 * The screen exists to answer "which of these models should I believe?"
 * without the three answers that are routinely wrong: the best in-sample fit,
 * the lowest information criterion by any margin at all, and a Bayes factor
 * read as if the prior had not been chosen by anyone. Every comparison number
 * here comes from `src/engine/modelchoice`, which reports the standard error
 * of the DIFFERENCE and says plainly when two models cannot be separated.
 *
 * What this file computes itself is only the model set: a nested family of
 * polynomial regressions, fitted by least squares through the engine's linear
 * algebra, plus the Gaussian log-likelihood and — for the evidence section —
 * the exact posterior of the known-variance g-prior model. Those are the
 * INPUTS to the comparison, written out here so they can be checked against
 * the formulas stated beside them. No ranking, weight, difference, standard
 * error or verdict on this screen is computed in this file.
 *
 * Two things are deliberately behind buttons. Cross-validation refits every
 * model once per fold, and evidence estimation draws a posterior and runs
 * bridge sampling; either can take seconds, and opening a tool must not freeze
 * the tab.
 */
