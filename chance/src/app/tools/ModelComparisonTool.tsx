/**
 * Built-in data: 40 points generated by an explicit rule, stated here and in
 * the interface, with a fixed linear congruential sequence so every machine
 * sees the same numbers. It is synthetic demonstration data, not a measured
 * dataset, and it is labelled as such wherever it appears.
 *
 *   x_i = i / 39 * 4 − 2,  y_i = 1 + 2x − 0.5x^2 + 0.3x^3 + e_i,  e_i ~ N(0, 1.2^2)
 *
 * The point of a cubic with this much noise is that degrees 3, 4 and 5 cannot
 * be separated by any amount of data this small — which is the situation the
 * standard errors on this screen exist to make visible.
 */
function builtInData(): { x: number; y: number }[] {
  let state = 20240917;
  const unit = (): number => {
    state = (1103515245 * state + 12345) % 2147483648;
    return (state + 0.5) / 2147483648;
  };
  const points: { x: number; y: number }[] = [];
  for (let i = 0; i < 40; i++) {
    const x = (i / 39) * 4 - 2;
    // Box-Muller from the same sequence, so the noise is reproducible too.
    const u1 = unit();
    const u2 = unit();
    const e = Math.sqrt(-2 * Math.log(u1)) * Math.cos(2 * Math.PI * u2);
    const y = 1 + 2 * x - 0.5 * x * x + 0.3 * x * x * x + 1.2 * e;
    points.push({ x, y: Math.round(y * 1e4) / 1e4 });
  }
  return points;
}

