/**
 * Sobol' sequence (base-2 digital net) with Gray-code construction and
 * randomisation.
 *
 * Construction. Dimension 1 is the van der Corput sequence in base 2.
 * Dimension j > 1 uses direction numbers m_1..m_s seeded from a primitive
 * polynomial of degree s over GF(2) and extended by the standard recurrence
 *
 *   m_i = 2 a_1 m_{i-1} ⊕ 4 a_2 m_{i-2} ⊕ … ⊕ 2^{s-1} a_{s-1} m_{i-s+1}
 *         ⊕ 2^s m_{i-s} ⊕ m_{i-s}
 *
 * (Bratley & Fox 1988; Joe & Kuo 2008). The direction numbers below are the
 * Joe–Kuo "new-joe-kuo-6" initial values, which are the published, widely used
 * table; the table is validated at load time (each m_i must be odd and less
 * than 2^i, which is the condition that makes every one-dimensional projection
 * a perfectly balanced (0,m,1)-net).
 *
 * Gray-code recurrence. Point n is obtained from point n−1 by a single XOR,
 * x_n = x_{n−1} ⊕ V[c] where c is the position of the lowest zero bit of n−1.
 * The sequence therefore costs O(d) per point. Index 0 is the origin; the
 * first 2^m points (indices 0 … 2^m−1) form a (t,m,d)-net.
 *
 * Randomisation. Plain Sobol has NO statistical error estimate. Two
 * randomisations are provided:
 *   - 'digital-shift': XOR every coordinate's bit string with an independent
 *     random 32-bit word (Cranley–Patterson in base 2). This is exact,
 *     unbiased, and provably preserves the net/balance property.
 *   - 'owen': nested uniform (Owen) scrambling implemented with the
 *     Laine–Karras/Burley keyed hash. This is a HASH APPROXIMATION to full
 *     nested uniform scrambling, not an exact realisation of it: the digit
 *     permutations are generated by a mixing function rather than drawn
 *     explicitly, which is how it is done in practice because exact nested
 *     scrambling of 32 bits needs 2^32 permutations per dimension. It is
 *     unbiased in the same way a digital shift is (each coordinate is marginally
 *     uniform and the scramble is independent of the integrand), and it
 *     additionally breaks the digit alignment that a pure shift leaves intact.
 *     Full, exactly-drawn Owen scrambling is NOT implemented; say so when
 *     citing results.
 */
