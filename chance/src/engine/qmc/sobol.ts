/** Maximum dimension this implementation can honestly produce. */
export const SOBOL_MAX_DIMENSION = DIRECTION_NUMBERS.length + 1;

/** Bits of resolution: indices must stay below 2^31. */
const BITS = 31;
const SCALE = 1 / 2 ** 32;

/** Validate the published table rather than trusting it blindly. */
function validateTable(): void {
  for (let k = 0; k < DIRECTION_NUMBERS.length; k++) {
    const row = DIRECTION_NUMBERS[k];
    const s = row[0];
    if (row.length !== s + 2) {
      throw new EngineError(
        `Sobol direction-number table is malformed at dimension ${k + 2}: expected ${s} initial values.`,
        'internal',
      );
    }
    for (let i = 1; i <= s; i++) {
      const m = row[i + 1];
      if (m % 2 !== 1 || m <= 0 || m >= 2 ** i) {
        throw new EngineError(
          `Sobol direction-number table is invalid at dimension ${k + 2}, m_${i} = ${m}: every m_i must be odd and below 2^i.`,
          'internal',
        );
      }
    }
  }
}
validateTable();

/** Direction vectors V[dim][bit], left-aligned to 32 bits. */
function buildDirections(dimension: number): Uint32Array[] {
  const out: Uint32Array[] = [];
  const v0 = new Uint32Array(BITS + 1);
  for (let i = 1; i <= BITS; i++) v0[i] = 1 << (32 - i);
  out.push(v0);
  for (let d = 1; d < dimension; d++) {
    const row = DIRECTION_NUMBERS[d - 1];
    const s = row[0];
    const a = row[1];
    const m = new Uint32Array(BITS + 1);
    for (let i = 1; i <= Math.min(s, BITS); i++) m[i] = row[i + 1];
    for (let i = s + 1; i <= BITS; i++) {
      let value = m[i - s] ^ ((m[i - s] << s) >>> 0);
      for (let k = 1; k <= s - 1; k++) {
        if ((a >>> (s - 1 - k)) & 1) value ^= (m[i - k] << k) >>> 0;
      }
      m[i] = value >>> 0;
    }
    const v = new Uint32Array(BITS + 1);
    for (let i = 1; i <= BITS; i++) v[i] = (m[i] << (32 - i)) >>> 0;
    out.push(v);
  }
  return out;
}

export type SobolRandomisation = 'none' | 'digital-shift' | 'owen';

export interface SobolOptions {
  dimension: number;
  randomisation?: SobolRandomisation;
  /** Required unless randomisation is 'none'. */
  seed?: Seed;
}

/** Reverse the bits of a 32-bit word. */
function reverseBits(x: number): number {
  let v = x >>> 0;
  v = ((v >>> 1) & 0x55555555) | ((v & 0x55555555) << 1);
  v = ((v >>> 2) & 0x33333333) | ((v & 0x33333333) << 2);
  v = ((v >>> 4) & 0x0f0f0f0f) | ((v & 0x0f0f0f0f) << 4);
  v = ((v >>> 8) & 0x00ff00ff) | ((v & 0x00ff00ff) << 8);
  return ((v >>> 16) | (v << 16)) >>> 0;
}

/** Laine–Karras permutation (Burley 2020), the hash behind Owen scrambling. */
function laineKarras(x: number, seed: number): number {
  let v = (x + seed) >>> 0;
  v = (v ^ Math.imul(v, 0x6c50b47c)) >>> 0;
  v = (v ^ Math.imul(v, 0xb82f1e52)) >>> 0;
  v = (v ^ Math.imul(v, 0xc7afe638)) >>> 0;
  v = (v ^ Math.imul(v, 0x8d22f6e6)) >>> 0;
  return v >>> 0;
}

/** Hash-based nested uniform (Owen) scramble of one coordinate's bit string. */
function owenScramble(x: number, seed: number): number {
  return reverseBits(laineKarras(reverseBits(x), seed)) >>> 0;
}

export class SobolSequence implements PointSequence {
  readonly name: string;
  readonly dimension: number;
  readonly randomised: boolean;
  private readonly directions: Uint32Array[];
  private readonly scramble: Uint32Array;
  private readonly mode: SobolRandomisation;
  /** Gray-code state: the integer coordinates of the last generated index. */
  private cursor = -1;
  private readonly state: Uint32Array;

  constructor(options: SobolOptions) {
    const { dimension } = options;
    const mode = options.randomisation ?? 'none';
    if (!Number.isInteger(dimension) || dimension < 1) {
      throw new EngineError('Sobol dimension must be a whole number of at least 1.', 'range');
    }
    if (dimension > SOBOL_MAX_DIMENSION) {
      throw new EngineError(
        `Sobol dimension ${dimension} exceeds the ${SOBOL_MAX_DIMENSION} dimensions for which this build has direction numbers. Add direction numbers for the higher dimensions, or use a lattice rule or Latin hypercube sampling instead; this module will not fabricate a sequence it cannot construct.`,
        'dimension',
      );
    }
    if (mode !== 'none' && options.seed === undefined) {
      throw new EngineError('A randomised Sobol sequence needs a seed so the randomisation can be reproduced.', 'required');
    }
    this.dimension = dimension;
    this.mode = mode;
    this.randomised = mode !== 'none';
    this.directions = buildDirections(dimension);
    this.scramble = new Uint32Array(dimension);
    if (mode !== 'none') {
      const rng = new Xoshiro128(`sobol:${String(options.seed)}`);
      for (let j = 0; j < dimension; j++) this.scramble[j] = rng.nextUint32();
    }
    this.state = new Uint32Array(dimension);
    this.name =
      mode === 'none'
        ? `Sobol (unrandomised, ${dimension}-d)`
        : mode === 'digital-shift'
          ? `Sobol with random digital shift (${dimension}-d)`
          : `Sobol with hash-based Owen scrambling (${dimension}-d)`;
  }

  fill(index: number, out: Float64Array): void {
    if (!Number.isInteger(index) || index < 0) {
      throw new EngineError('Sobol point index must be a non-negative whole number.', 'range');
    }
    if (index >= 2 ** BITS) {
      throw new EngineError(`Sobol point index must be below 2^${BITS}.`, 'range');
    }
    if (index !== this.cursor + 1) this.seek(index);
    else this.advance(index);
    const d = this.dimension;
    for (let j = 0; j < d; j++) {
      const raw = this.state[j];
      const bits =
        this.mode === 'none'
          ? raw
          : this.mode === 'digital-shift'
            ? (raw ^ this.scramble[j]) >>> 0
            : owenScramble(raw, this.scramble[j]);
      out[j] = (bits >>> 0) * SCALE;
    }
  }

  point(index: number): Float64Array {
    const out = new Float64Array(this.dimension);
    this.fill(index, out);
    return out;
  }

  /** Reset and walk forward to `index` (Gray code needs sequential access). */
  private seek(index: number): void {
    this.state.fill(0);
    this.cursor = 0;
    for (let n = 1; n <= index; n++) this.advance(n);
    this.cursor = index;
  }

  private advance(index: number): void {
    if (index === 0) {
      this.state.fill(0);
      this.cursor = 0;
      return;
    }
    // Position (1-based) of the lowest zero bit of index-1.
    const prev = index - 1;
    let c = 1;
    let v = prev;
    while (v & 1) {
      v >>>= 1;
      c++;
    }
    const d = this.dimension;
    for (let j = 0; j < d; j++) this.state[j] = (this.state[j] ^ this.directions[j][c]) >>> 0;
    this.cursor = index;
  }
}

export function sobolSequence(options: SobolOptions): SobolSequence {
  return new SobolSequence(options);
}
