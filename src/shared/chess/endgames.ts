/**
 * The Endgame Lab: the endings themselves, how a claim about one is proved, and what happens while somebody plays it
 * (Sections 141-150).
 *
 * ## Why a position needs a proof
 *
 * An endgame exercise is a claim, and an endgame claim is unusually easy to get wrong while looking right. "Mate in
 * three" that is really mate in four, "White wins" from a position that is drawn by a tempo, a Lucena position with
 * the rook on the wrong file: all of them look exactly like the correct version on a board. Somebody then spends ten
 * minutes failing to do something impossible and concludes they cannot play endings.
 *
 * So the catalogue in `endgamesData.ts` is data, and this file is the machine that checks it. `verifyEntry` recomputes
 * what an entry claims instead of believing it:
 *
 *   - **mate in n** is settled completely, by exhaustive search. Every defence is tried, so one unlisted reply cannot
 *     hide. The search also proves there is no mate in fewer, which is what makes "in n" mean n.
 *   - **a forced promotion in n** is settled the same way, with promotion as the goal instead of mate.
 *   - **a forced draw in n** is settled the same way, with "the rules say this is drawn" as the goal.
 *   - **win**, **technique** and **a draw held for n moves** are NOT settled by search. Nothing here can prove that
 *     king and pawn beats king: that needs a tablebase, and inventing the answer would be worse than saying so. What
 *     is checked for those is everything that can be: the position is legal, the stated side really is to move, the
 *     objective is not already met before the first move, and the authored model line is playable from the position
 *     and does reach the objective. The entry's own `provenance` says where the assessment comes from, and the screen
 *     says plainly which of the two kinds of checking an entry has had.
 *
 * ## Why the search is built on `rules.ts` and is deliberately small
 *
 * There is one authority on chess in Orbis and this is not it. Every position the search looks at is generated by
 * `legalMoves`, so the search cannot disagree with the board about what is legal. That costs speed -- the authority
 * builds a full description of every move -- so the search is kept honest about its limits instead of being made
 * clever: it takes a node budget, and when it runs out it says `complete: false` rather than returning an answer it
 * did not earn. A `false` from an incomplete search means "not proved", never "not true".
 *
 * ## The defence is a rule, not an opponent
 *
 * A drill needs somebody to play the other side. Where the ending has a defence worth knowing -- Philidor's third
 * rank, the rook check from behind in Lucena -- the entry carries those moves and the drill plays them. Everywhere
 * else the defence comes from the ladder in `DEFENCE_RULES`: take a mate, take a draw, take a free piece, avoid
 * walking into mate, and otherwise go where a defender is supposed to go. It is deterministic, so a drill replays
 * identically, and it is weak, which the screen says out loud. Beating it is not proof that the technique is known.
 *
 * Pure: no storage, no clock, no engine, no Electron.
 */

