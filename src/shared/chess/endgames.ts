export const PIECE_NAME: Record<PieceLetter, string> = NAME

// ---------------------------------------------------------------- proving something is forced

/** What a search is looking for. */
export type Goal = 'mate' | 'promote' | 'draw'

export const GOAL_LABEL: Record<Goal, string> = {
  mate: 'checkmate',
  promote: 'a promotion',
  draw: 'a draw by the rules'
}

export interface SearchLimits {
  /** Positions the search may look at before it gives up. */
  budget?: number
}

export interface SearchResult {
  /** The number of the mover's own moves needed, when a forced line was proved. Null when none was. */
  moves: number | null
  /** False when the budget ran out first. A null `moves` from an incomplete search means "not proved", not "no". */
  complete: boolean
  nodes: number
}

interface Context {
  goal: Goal
  budget: number
  nodes: number
  stopped: boolean
  /** `${positionKey}|${depth}` to whether the mover can force the goal within `depth` of its own moves. */
  memo: Map<string, boolean>
  /** Legal moves by position, because the authority rebuilds them from the FEN every time it is asked. */
  moves: Map<string, ChessMove[]>
}

function movesIn(ctx: Context, fen: string): ChessMove[] {
  const key = positionKey(fen)
  const had = ctx.moves.get(key)
  if (had) return had
  const made = movesOf(fen)
  ctx.moves.set(key, made)
  return made
}

/** Did this move achieve the goal, on its own, the moment it was played? */
function achieves(move: ChessMove, goal: Goal): boolean {
  if (goal === 'mate') return move.checkmate
  if (goal === 'promote') return move.promotion !== undefined
  const after = outcome(move.after)
  return after.over && after.result === '1/2-1/2'
}

/**
 * Moves worth trying first.
 *
 * Ordering changes nothing about the answer -- every move is still tried before a node fails -- but a forced line
 * usually starts with a check, a capture or a pawn going forward, and finding it early saves the rest of the list.
 */
function ordered(moves: ChessMove[], goal: Goal): ChessMove[] {
  const rank = (m: ChessMove): number => {
    if (goal === 'promote') return (m.promotion ? 0 : 4) + (m.piece === 'p' ? 0 : 1)
    if (goal === 'draw') return (m.captured ? 0 : 2) + (m.check ? 0 : 1)
    return (m.check ? 0 : 3) + (m.captured ? 0 : 1)
  }
  return [...moves].sort((a, b) => rank(a) - rank(b) || (a.uci < b.uci ? -1 : 1))
}

/** Can the side to move force the goal within `depth` of its own moves? */
function canForce(ctx: Context, fen: string, depth: number): boolean {
  if (ctx.stopped || depth <= 0) return false
  const key = `${positionKey(fen)}|${depth}`
  const remembered = ctx.memo.get(key)
  if (remembered !== undefined) return remembered
  ctx.nodes += 1
  if (ctx.nodes > ctx.budget) { ctx.stopped = true; return false }

  const moves = movesIn(ctx, fen)
  if (!moves.length) return false
  for (const move of moves) {
    if (achieves(move, ctx.goal)) { ctx.memo.set(key, true); return true }
  }
  if (depth === 1) { ctx.memo.set(key, false); return false }

  for (const move of ordered(moves, ctx.goal)) {
    const replies = movesIn(ctx, move.after)
    // The defender having no move at all is checkmate or stalemate, and either would have been caught above as the
    // goal or is a dead end for it. Nothing to recurse into.
    if (!replies.length) continue
    let every = true
    for (const reply of replies) {
      if (!canForce(ctx, reply.after, depth - 1)) { every = false; break }
      if (ctx.stopped) return false
    }
    if (ctx.stopped) return false
    if (every) { ctx.memo.set(key, true); return true }
  }
  if (ctx.stopped) return false
  ctx.memo.set(key, false)
  return false
}

function newContext(goal: Goal, limits: SearchLimits): Context {
  return { goal, budget: limits.budget ?? 120_000, nodes: 0, stopped: false, memo: new Map(), moves: new Map() }
}

/**
 * The fewest of the mover's own moves that force the goal, searching one move deeper at a time so the answer is the
 * shortest one and "in n" means n.
 */
export function forcedIn(fen: string, goal: Goal, maxMoves: number, limits: SearchLimits = {}): SearchResult {
  if (!playable(fen).ok) return { moves: null, complete: true, nodes: 0 }
  const ctx = newContext(goal, limits)
  for (let depth = 1; depth <= maxMoves; depth++) {
    if (canForce(ctx, fen, depth)) return { moves: depth, complete: true, nodes: ctx.nodes }
    if (ctx.stopped) return { moves: null, complete: false, nodes: ctx.nodes }
  }
  return { moves: null, complete: !ctx.stopped, nodes: ctx.nodes }
}

/**
 * The same question from the other side of a move: the goal's side has just played, the opponent is to move, and the
 * answer counts only the goal side's remaining moves. This is what says whether a mate is still forced after the move
 * somebody actually made.
 */
export function forcedAfter(fen: string, goal: Goal, maxMoves: number, limits: SearchLimits = {}): SearchResult {
  if (!playable(fen).ok) return { moves: null, complete: true, nodes: 0 }
  const state = outcome(fen)
  if (goal === 'mate' && state.over && state.reason === 'checkmate') return { moves: 0, complete: true, nodes: 0 }
  if (goal === 'draw' && state.over && state.result === '1/2-1/2') return { moves: 0, complete: true, nodes: 0 }
  const ctx = newContext(goal, limits)
  const replies = movesIn(ctx, fen)
  if (!replies.length) return { moves: null, complete: true, nodes: 0 }
  for (let depth = 1; depth <= maxMoves; depth++) {
    let every = true
    for (const reply of replies) {
      if (!canForce(ctx, reply.after, depth)) { every = false; break }
    }
    if (ctx.stopped) return { moves: null, complete: false, nodes: ctx.nodes }
    if (every) return { moves: depth, complete: true, nodes: ctx.nodes }
  }
  return { moves: null, complete: !ctx.stopped, nodes: ctx.nodes }
}

/** Mate, said the way an exercise says it: the number of the mover's moves, or null. */
export function mateIn(fen: string, maxMoves: number, limits: SearchLimits = {}): SearchResult {
  return forcedIn(fen, 'mate', maxMoves, limits)
}

// ---------------------------------------------------------------- is the objective met, and has it been lost

/** What the learner is being asked for, in a sentence anybody can act on. */
export function objectiveText(entry: EndgameEntry): string {
  const o = entry.objective
  const you = entry.sideToMove === 'w' ? 'White' : 'Black'
  if (o.kind === 'mate-in') return `You are ${you}. Force checkmate in ${o.moves} ${o.moves === 1 ? 'move' : 'moves'}.`
  if (o.kind === 'win') return `You are ${you}. Checkmate the defending king. There is no move limit.`
  if (o.kind === 'promote') {
    return o.moves === undefined
      ? `You are ${you}. Get a pawn to the end of the board.`
      : `You are ${you}. Get a pawn to the end of the board; it can be forced in ${o.moves}.`
  }
  if (o.kind === 'draw') {
    return o.forcedIn === undefined
      ? `You are ${you}. Hold the draw for ${o.holdMoves} of your own moves.`
      : `You are ${you}. Force a drawn position in ${o.forcedIn} ${o.forcedIn === 1 ? 'move' : 'moves'}.`
  }
  const goal = o.goal
  const within = o.within === undefined ? '' : ` Do it within ${o.within} moves.`
  if (goal.kind === 'no-pawns') return `You are ${you}. Catch the pawn and take it.${within}`
  if (goal.kind === 'king-on') {
    return `You are ${you}. Get your king to ${listSquares(goal.squares)}${goal.thenOpponentToMove ? ' with the other side to move' : ''}.${within}`
  }
  return `You are ${you}. Get your ${NAME[goal.piece]} to ${listSquares(goal.squares)}.${within}`
}

function listSquares(squares: readonly string[]): string {
  if (squares.length === 1) return squares[0]
  return `${squares.slice(0, -1).join(', ')} or ${squares[squares.length - 1]}`
}

/**
 * Everything the judge needs that a FEN alone does not carry.
 *
 * A promotion is a fact about what was played, so it is counted here rather than guessed from the pieces on the
 * board: a queen beside a king could have been there all along.
 */
export interface Progress {
  /** Every position from the start, in order, including the one now. */
  fens: readonly string[]
  /** The notation of every half-move played. */
  san: readonly string[]
  /** The learner's own moves so far. */
  learnerMoves: number
  /** True when the learner has promoted a pawn at some point in this drill. */
  learnerPromoted: boolean
  /** True when the defender has promoted a pawn at some point in this drill. */
  defencePromoted: boolean
}

/**
 * The ways a defensive stand has already failed, said plainly, or an empty string while it is holding.
 *
 * Kept apart from the rest of the judging so that "the draw is held" and "the draw is broken" are decided by the same
 * two facts and cannot drift into disagreeing with each other.
 */
function drawBroken(entry: EndgameEntry, fen: string, progress: Progress): string {
  const learner = entry.sideToMove
  const state = outcome(fen, [...progress.san])
  if (state.over && state.reason === 'checkmate' && sideToMove(fen) === learner) return 'Your own king has been checkmated.'
  if (entry.objective.kind === 'draw' && entry.objective.lostIf === 'opponent-promotes' && progress.defencePromoted) {
    return 'The pawn has promoted. That is what the defence was there to stop.'
  }
  return ''
}

/** Is the objective achieved in this position? */
export function objectiveMet(entry: EndgameEntry, fen: string, progress: Progress): boolean {
  const learner = entry.sideToMove
  const o = entry.objective
  const state = outcome(fen, [...progress.san])
  const mated = state.over && state.reason === 'checkmate' && sideToMove(fen) !== learner
  if (o.kind === 'mate-in' || o.kind === 'win') return mated
  if (o.kind === 'promote') return progress.learnerPromoted
  if (o.kind === 'draw') {
    if (state.over && state.result === '1/2-1/2') return true
    if (o.forcedIn !== undefined) return false
    return progress.learnerMoves >= o.holdMoves && drawBroken(entry, fen, progress) === ''
  }
  const goal = o.goal
  if (goal.kind === 'no-pawns') return piecesOf(fen, other(learner)).every((p) => p.type !== 'p')
  if (goal.kind === 'king-on') {
    const king = piecesOf(fen, learner).find((p) => p.type === 'k')
    if (!king || !goal.squares.includes(king.square)) return false
    return goal.thenOpponentToMove !== true || sideToMove(fen) !== learner
  }
  return piecesOf(fen, learner).some((p) => p.type === goal.piece && goal.squares.includes(p.square))
}

/** Has the objective been put out of reach, and what was lost when it went? */
export function objectiveLost(entry: EndgameEntry, fen: string, progress: Progress): { lost: boolean; because: string } {
  const learner = entry.sideToMove
  const o = entry.objective
  const state = outcome(fen, [...progress.san])
  const learnerMated = state.over && state.reason === 'checkmate' && sideToMove(fen) === learner
  if (learnerMated) return { lost: true, because: 'Your own king has been checkmated.' }

  const wantsAWin = o.kind === 'mate-in' || o.kind === 'win' || o.kind === 'promote'
  if (wantsAWin && state.over && state.result === '1/2-1/2') {
    const why = state.reason === 'stalemate'
      ? 'That is stalemate: the defending king has no move and is not in check, so the game is drawn and the win is gone.'
      : state.reason === 'insufficient-material'
        ? 'Neither side has enough left to checkmate, so the game is drawn and the win is gone.'
        : state.reason === 'threefold'
          ? 'The same position has come up three times, so the game is drawn and the win is gone.'
          : 'Fifty moves have passed with no capture and no pawn move, so the game is drawn and the win is gone.'
    return { lost: true, because: why }
  }
  if (o.kind === 'promote' && !progress.learnerPromoted && !piecesOf(fen, learner).some((p) => p.type === 'p')) {
    return { lost: true, because: 'The pawn has gone, and with it everything there was to play for.' }
  }
  if (o.kind === 'mate-in' && progress.learnerMoves >= o.moves && !objectiveMet(entry, fen, progress)) {
    return { lost: true, because: `The mate was there in ${o.moves}; ${o.moves} ${o.moves === 1 ? 'move' : 'moves'} have gone by and the king is not mated.` }
  }
  if (o.kind === 'draw') {
    const broken = drawBroken(entry, fen, progress)
    if (broken) return { lost: true, because: broken }
    if (o.forcedIn !== undefined && progress.learnerMoves >= o.forcedIn && !objectiveMet(entry, fen, progress)) {
      return { lost: true, because: `The draw was there to be forced in ${o.forcedIn}; the moves have gone and the position is not drawn.` }
    }
  }
  if (o.kind === 'technique') {
    if (o.goal.kind === 'no-pawns' && progress.defencePromoted) {
      return { lost: true, because: 'The pawn has promoted: it was not caught in time.' }
    }
    if (o.within !== undefined && progress.learnerMoves >= o.within && !objectiveMet(entry, fen, progress)) {
      return { lost: true, because: `That was ${o.within} moves, which is all this one allows.` }
    }
  }
  // A side with no legal move left and no objective met has nowhere to go.
  if (state.over && state.reason === 'stalemate' && o.kind === 'technique' && !objectiveMet(entry, fen, progress)) {
    return { lost: true, because: 'There is no legal move left and the job is not done.' }
  }
  return { lost: false, because: '' }
}

// ---------------------------------------------------------------- the defence

/**
 * The ladder the defence follows when the entry has not written a reply for the position.
 *
 * It is shown on screen, because a learner is entitled to know what they are beating.
 */
export const DEFENCE_RULES: readonly string[] = [
  'If a move gives checkmate, it plays it.',
  'If a move makes the position drawn by the rules, it plays that.',
  'If a piece can be taken and nothing can take back, it takes the most valuable one.',
  'It will not play a move that lets you mate immediately, if it has another move.',
  'It pushes its own most advanced pawn whenever the push cannot simply be taken.',
  'Otherwise the king heads for the square your most advanced pawn is going to, or for the middle of the board when you have no pawn; another piece goes to the file or rank of that pawn.',
  'Equal moves are settled by the same tie-break every time, so a drill replays exactly.'
]

export interface DefenceChoice {
  move: ChessMove
  /** Whether this came from the entry's own defensive line or from the general rule. */
  source: 'authored' | 'rule'
  /** Why the defence played it. */
  why: string
}

/** Does the side to move have a mate in one here? Used to keep the defence from walking into one. */
function mateInOne(fen: string): boolean {
  return movesOf(fen).some((m) => m.checkmate)
}

/** The defence's move in this position, or null when it has none because the game is over. */
export function defenceReply(entry: EndgameEntry, fen: string): DefenceChoice | null {
  const learner = entry.sideToMove
  if (sideToMove(fen) === learner) return null
  const moves = movesOf(fen)
  if (!moves.length) return null

  const written = (entry.defence ?? []).find((d) => positionKey(d.fen) === positionKey(fen))
  if (written) {
    const made = applyMove(fen, written.play)
    // An authored reply that is not legal here is a bug in the data, caught by the catalogue check. The drill does not
    // stop for it: it falls through to the rule so a learner is never stuck.
    if (made) return { move: made, source: 'authored', why: written.why }
  }

  const mate = moves.find((m) => m.checkmate)
  if (mate) return { move: mate, source: 'rule', why: 'It is checkmate, so the defence plays it.' }

  const draws = moves
    .filter((m) => { const after = outcome(m.after); return after.over && after.result === '1/2-1/2' })
    .sort((a, b) => (a.uci < b.uci ? -1 : 1))
  if (draws.length) return { move: draws[0], source: 'rule', why: 'That makes the position drawn by the rules, which is all the defence wants.' }

  const free = freeCapture(fen)
  if (free) return { move: free.move, source: 'rule', why: `The ${NAME[free.move.captured ?? 'p']} could be taken and nothing takes back.` }

  const safe = moves.filter((m) => !mateInOne(m.after))
  const pool = safe.length ? safe : moves

  // A defender with a pawn of its own has one plan, and it is the plan the learner has to stop: push it. Without this
  // the defence would shuffle its king while the pawn stood still, and a drill about catching a runner would never
  // have a runner to catch.
  const ownPawn = leadingPawn(fen, other(learner))
  if (ownPawn) {
    const pushes = pool
      .filter((m) => m.piece === 'p' && m.from === ownPawn && !m.captured)
      .filter((m) => {
        const answer = freeCapture(m.after)
        return !answer || answer.move.to !== m.to
      })
      .sort((a, b) => (a.uci < b.uci ? -1 : 1))
    if (pushes.length) {
      const push = pushes[0]
      return { move: push, source: 'rule', why: `The pawn goes on to ${push.to}; that is the only thing this side has.` }
    }
  }

  const pawn = leadingPawn(fen, learner)
  const target = pawn ? promotionSquare(pawn, learner) : null
  const score = (m: ChessMove): number => {
    if (m.piece === 'k') {
      // Toward the queening square when there is a pawn to stop; otherwise into the middle, away from the edge.
      return target ? -kingSteps(m.to, target) : fromEdge(m.to)
    }
    if (!pawn) return -1
    // A piece belongs on the file or the rank of the pawn it is fighting: that is where it can stop or take it.
    return (m.to[0] === pawn[0] ? 1 : 0) + (m.to[1] === pawn[1] ? 1 : 0) - 2
  }
  const best = [...pool].sort((a, b) => score(b) - score(a) || (a.uci < b.uci ? -1 : 1))[0]
  const why = best.piece === 'k'
    ? target
      ? `The king goes toward ${target}, the square your pawn is heading for.`
      : 'The king heads for the middle, away from the edge where it gets mated.'
    : pawn
      ? `It puts the ${NAME[best.piece]} on the line of your pawn.`
      : `There is nothing better by the rule, so it plays the first move the tie-break gives.`
  return { move: best, source: 'rule', why }
}

// ---------------------------------------------------------------- playing a drill

export type DrillStatus = 'playing' | 'achieved' | 'lost'

export interface DrillMove {
  san: string
  uci: string
  fen: string
  by: 'learner' | 'defence'
  /** For a defence move: why it was played. */
  note?: string
}

export interface DrillState {
  entryId: string
  learner: Side
  /** The position to play from now. */
  fen: string
  moves: readonly DrillMove[]
  status: DrillStatus
  /** Where things stand, in one sentence. */
  message: string
  /** Set when the objective has gone: what was lost. */
  slip?: string
}

/** A fresh attempt at an ending. */
export function startDrill(entry: EndgameEntry): DrillState {
  return {
    entryId: entry.id,
    learner: entry.sideToMove,
    fen: entry.fen,
    moves: [],
    status: 'playing',
    message: objectiveText(entry)
  }
}

export function progressOf(entry: EndgameEntry, state: DrillState): Progress {
  return {
    fens: [entry.fen, ...state.moves.map((m) => m.fen)],
    san: state.moves.map((m) => m.san),
    learnerMoves: state.moves.filter((m) => m.by === 'learner').length,
    learnerPromoted: state.moves.some((m) => m.by === 'learner' && m.san.includes('=')),
    defencePromoted: state.moves.some((m) => m.by === 'defence' && m.san.includes('='))
  }
}

export interface DrillOutcome {
  state: DrillState
  /** False when the move could not be played: the state is unchanged. */
  accepted: boolean
  /** What to say about the move that was just made. */
  feedback: string
}

export interface DrillOptions {
  /**
   * Whether to spend a search on saying what a move did to a forced mate. It is only worth it when the mate left is
   * short, and the budget keeps it from stalling a screen.
   */
  judge?: boolean
  budget?: number
}

/**
 * The learner's move, the defence's answer, and the position judged after each of them.
 *
 * The judgement never asks whether the move matches a line. A mate is a mate because the king is mated; a promotion
 * is a promotion because a pawn promoted. That is what lets a learner win an ending a different way from the author
 * and be told they have done it (Section 147).
 */
export function drillMove(entry: EndgameEntry, state: DrillState, move: MoveInput, options: DrillOptions = {}): DrillOutcome {
  if (state.status !== 'playing') {
    return { state, accepted: false, feedback: 'This drill is over. Start it again to play it from the beginning.' }
  }
  const made = applyMove(state.fen, move)
  if (!made) {
    return { state, accepted: false, feedback: 'That move cannot be played in this position, so nothing has changed.' }
  }

  const afterLearner: DrillState = {
    ...state,
    fen: made.after,
    moves: [...state.moves, { san: made.san, uci: made.uci, fen: made.after, by: 'learner' }]
  }
  const parts: string[] = []

  const settledNow = settle(entry, afterLearner)
  if (settledNow) return { state: settledNow, accepted: true, feedback: settledNow.status === 'achieved' ? settledNow.message : (settledNow.slip ?? settledNow.message) }

  // Nothing is decided, so say what can be said about the move and let the defence answer.
  const comment = judgeMove(entry, state, made, options)
  if (comment) parts.push(comment)

  const reply = defenceReply(entry, afterLearner.fen)
  if (!reply) {
    // No legal reply and the game is not over by the rules should be impossible; if it happens, say so rather than
    // pretending the drill is still running.
    return {
      state: { ...afterLearner, status: 'lost', message: 'The defence has no legal move and the rules do not call this over. Orbis cannot go on from here.', slip: 'Nothing more can be played from this position.' },
      accepted: true,
      feedback: 'The defence has no move here and the position is not a result Orbis recognises.'
    }
  }

  const afterDefence: DrillState = {
    ...afterLearner,
    fen: reply.move.after,
    moves: [...afterLearner.moves, { san: reply.move.san, uci: reply.move.uci, fen: reply.move.after, by: 'defence', note: reply.why }]
  }
  const settledAfter = settle(entry, afterDefence)
  if (settledAfter) {
    const said = settledAfter.status === 'achieved' ? settledAfter.message : (settledAfter.slip ?? settledAfter.message)
    return { state: settledAfter, accepted: true, feedback: [...parts, said].join(' ') }
  }

  const standing = `${reply.move.san} — ${reply.why}`
  return {
    state: { ...afterDefence, message: standing, ...(afterDefence.slip ? { slip: afterDefence.slip } : {}) },
    accepted: true,
    feedback: [...parts, standing].join(' ')
  }
}

/** Achieved, lost, or neither. Returns null when the drill goes on. */
function settle(entry: EndgameEntry, state: DrillState): DrillState | null {
  const progress = progressOf(entry, state)
  if (objectiveMet(entry, state.fen, progress)) {
    return { ...state, status: 'achieved', message: achievedText(entry, state, progress) }
  }
  const lost = objectiveLost(entry, state.fen, progress)
  if (lost.lost) {
    return { ...state, status: 'lost', message: 'The objective has gone.', slip: lost.because }
  }
  return null
}

function achievedText(entry: EndgameEntry, state: DrillState, progress: Progress): string {
  const o = entry.objective
  const own = progress.learnerMoves
  if (o.kind === 'mate-in') return `Checkmate, in ${own} ${own === 1 ? 'move' : 'moves'}. That is the objective.`
  if (o.kind === 'win') return `Checkmate after ${own} of your moves. That is the ending won.`
  if (o.kind === 'promote') return 'The pawn is through. That is the objective.'
  if (o.kind === 'draw') {
    const state2 = outcome(state.fen, [...progress.san])
    if (state2.over) return `Drawn — ${state2.reason.replace('-', ' ')}. The defence held.`
    return `${own} moves held without the defence breaking. That is the objective.`
  }
  const goal = o.goal
  if (goal.kind === 'no-pawns') return 'The pawn is off the board. There is nothing left to promote.'
  if (goal.kind === 'king-on') {
    return goal.thenOpponentToMove === true
      ? 'Your king is where it needed to be, and it is the other side to move. That is the objective.'
      : 'Your king is where it needed to be. That is the objective.'
  }
  return `Your ${NAME[goal.piece]} is where it needed to be. That is the objective.`
}

/**
 * What can honestly be said about the move just played.
 *
 * Two things only, and both are facts: a piece left where it can be taken for nothing, and -- when the search can
 * afford it -- what the move did to a forced mate. Everything else in an endgame needs a tablebase, and a sentence
 * about a position Orbis has not assessed would be a guess dressed as feedback.
 */
function judgeMove(entry: EndgameEntry, before: DrillState, made: ChessMove, options: DrillOptions): string {
  const notes: string[] = []
  const free = freeCapture(made.after)
  if (free && free.move.captured) {
    notes.push(`Careful: your ${NAME[free.move.captured]} can be taken on ${free.move.to} and nothing takes back.`)
  }

  if (options.judge === true && entry.objective.kind === 'mate-in') {
    const allowed = entry.objective.moves
    const used = before.moves.filter((m) => m.by === 'learner').length + 1
    const left = allowed - used
    // Only when the mate left is short: proving one takes a search, and a long one would stall the screen.
    if (left >= 1 && left <= 2) {
      const was = forcedAfter(made.after, 'mate', left, { budget: options.budget ?? 20_000 })
      if (!was.complete) notes.push('Orbis could not work out in time whether the mate is still forced, so it is not saying.')
      else if (was.moves === null) notes.push(`From here there is no longer a forced mate in the ${left} ${left === 1 ? 'move' : 'moves'} left.`)
      else if (was.moves < left) notes.push(`The mate is still forced, and now in ${was.moves}.`)
      else notes.push('The mate is still forced.')
    }
  }
  return notes.join(' ')
}

/**
 * The next move of the entry's own line, when the drill has followed that line exactly so far.
 *
 * Off the line there is no hint, and it says so. A made-up hint in an ending is worse than none: it would be the
 * one place a learner trusts completely.
 */
export function hintFor(entry: EndgameEntry, state: DrillState): { san?: string; text: string } {
  const line = entry.line ?? []
  if (!line.length) return { text: 'This ending has no written line, so Orbis has no move to show you.' }
  if (state.moves.length >= line.length) return { text: 'The written line has run out.' }
  let fen = entry.fen
  for (const [index, played] of state.moves.entries()) {
    const expected = applyMove(fen, line[index])
    if (!expected || expected.uci !== played.uci) {
      return { text: 'You are away from the written line, so Orbis has no move to show you here. The objective is still judged from the position.' }
    }
    fen = expected.after
  }
  const next = applyMove(fen, line[state.moves.length])
  if (!next) return { text: 'The written line cannot be played from here.' }
  return { san: next.san, text: `The line plays ${next.san}.` }
}

// ---------------------------------------------------------------- checking the catalogue

export interface EntryCheck {
  id: string
  /** False when something is wrong with the entry. A failing entry is a bug in the data. */
  ok: boolean
  problems: string[]
  /** What a machine settled, in plain words. */
  proved: string[]
  /** What no machine here can settle, and why. */
  unproved: string[]
  nodes: number
}

export interface VerifyOptions extends SearchLimits {
  /** Skip the searches, for a quick check of the data's shape. */
  searches?: boolean
}

const SQUARE = /^[a-h][1-8]$/

/** Everything that can be checked about one entry, checked. */
export function verifyEntry(entry: EndgameEntry, options: VerifyOptions = {}): EntryCheck {
  const problems: string[] = []
  const proved: string[] = []
  const unproved: string[] = []
  let nodes = 0
  const search = options.searches !== false

  if (!/^[a-z][a-z0-9-]{3,48}$/.test(entry.id)) problems.push('The id is not a plain lower-case name.')
  if (!entry.title.trim()) problems.push('There is no title.')
  const sentences = entry.method.trim().split(/(?<=[.!?])\s+/).filter(Boolean)
  if (entry.method.trim().length < 20) problems.push('The method does not say anything.')
  if (sentences.length > 2) problems.push(`The method runs to ${sentences.length} sentences; one or two is the rule.`)
  if (!/[.!?]$/.test(entry.method.trim())) problems.push('The method does not finish its sentence.')
  if (!entry.provenance.trim()) problems.push('There is no provenance.')
  if (![1, 2, 3, 4, 5].includes(entry.difficulty)) problems.push('The difficulty is not between 1 and 5.')
  for (const square of entry.marks ?? []) if (!SQUARE.test(square)) problems.push(`"${square}" is not a square.`)

  const legal = playable(entry.fen)
  if (!legal.ok) {
    problems.push(`The position is not one a game could reach: ${legal.reason ?? 'no reason given'}`)
    // Nothing below this would mean anything, and some of it would raise an error on a position that cannot exist.
    return { id: entry.id, ok: false, problems, proved, unproved, nodes }
  }
  proved.push('The position is legal and could be reached in a game.')
  if (!movesOf(entry.fen).length) problems.push('There is no legal move in this position, so there is nothing to play.')
  if (sideToMove(entry.fen) !== entry.sideToMove) {
    problems.push(`The entry says ${entry.sideToMove === 'w' ? 'White' : 'Black'} to move and the position says ${sideToMove(entry.fen) === 'w' ? 'White' : 'Black'}.`)
  } else {
    proved.push(`${entry.sideToMove === 'w' ? 'White' : 'Black'} really is to move.`)
  }

  const fresh = startDrill(entry)
  const atStart = progressOf(entry, fresh)
  if (objectiveMet(entry, entry.fen, atStart)) problems.push('The objective is already met before a move is played, so there is nothing to do.')
  else proved.push('The objective is not already met at the start.')
  if (objectiveLost(entry, entry.fen, atStart).lost) problems.push('The objective is already out of reach before a move is played.')

  // The objective's own claim.
  const o = entry.objective
  if (o.kind === 'mate-in') {
    if (!Number.isInteger(o.moves) || o.moves < 1 || o.moves > 8) problems.push('A mate in n needs n between 1 and 8.')
    else if (search) {
      const found = mateIn(entry.fen, o.moves + 1, options)
      nodes += found.nodes
      if (!found.complete) unproved.push(`The mate search ran out of its budget after ${found.nodes} positions, so the claim is unproved.`)
      else if (found.moves === null) problems.push(`No forced mate in ${o.moves + 1} or fewer exists here, so "mate in ${o.moves}" is wrong.`)
      else if (found.moves !== o.moves) problems.push(`The forced mate is in ${found.moves}, not ${o.moves}.`)
      else proved.push(`Checkmate is forced in exactly ${o.moves} against every defence (${found.nodes} positions searched).`)
    }
  } else if (o.kind === 'promote') {
    if (!piecesOf(entry.fen, entry.sideToMove).some((p) => p.type === 'p')) problems.push('There is no pawn to promote.')
    if (o.moves !== undefined) {
      if (!Number.isInteger(o.moves) || o.moves < 1 || o.moves > 8) problems.push('A forced promotion in n needs n between 1 and 8.')
      else if (search) {
        const found = forcedIn(entry.fen, 'promote', o.moves + 1, options)
        nodes += found.nodes
        if (!found.complete) unproved.push(`The promotion search ran out of its budget after ${found.nodes} positions, so the claim is unproved.`)
        else if (found.moves === null) problems.push(`No forced promotion in ${o.moves + 1} or fewer exists here.`)
        else if (found.moves !== o.moves) problems.push(`The forced promotion is in ${found.moves}, not ${o.moves}.`)
        else proved.push(`A promotion is forced in exactly ${o.moves} against every defence (${found.nodes} positions searched).`)
      }
    } else {
      unproved.push('That the pawn gets through at all is standard theory, not something searched here.')
    }
  } else if (o.kind === 'draw') {
    if (!Number.isInteger(o.holdMoves) || o.holdMoves < 1 || o.holdMoves > 40) problems.push('Holding a draw needs a number of moves between 1 and 40.')
    if (o.forcedIn !== undefined) {
      if (search) {
        const found = forcedIn(entry.fen, 'draw', o.forcedIn + 1, options)
        nodes += found.nodes
        if (!found.complete) unproved.push(`The draw search ran out of its budget after ${found.nodes} positions, so the claim is unproved.`)
        else if (found.moves === null) problems.push(`No forced draw in ${o.forcedIn + 1} or fewer exists here.`)
        else if (found.moves !== o.forcedIn) problems.push(`The forced draw is in ${found.moves}, not ${o.forcedIn}.`)
        else proved.push(`A position drawn by the rules is forced in exactly ${o.forcedIn} (${found.nodes} positions searched).`)
      }
    } else {
      unproved.push('That the draw can be held against any defence is standard theory; what is checked is the line and the holding count.')
    }
  } else if (o.kind === 'win') {
    unproved.push('That this is won needs a tablebase or an engine; nothing here proves it. The provenance says where the assessment comes from.')
  } else {
    const goal = o.goal
    if (goal.kind === 'king-on' || goal.kind === 'piece-on') {
      if (!goal.squares.length) problems.push('The objective names no square.')
      for (const square of goal.squares) if (!SQUARE.test(square)) problems.push(`"${square}" is not a square.`)
    }
    if (goal.kind === 'piece-on' && !piecesOf(entry.fen, entry.sideToMove).some((p) => p.type === goal.piece)) {
      problems.push(`There is no ${NAME[goal.piece]} to put anywhere.`)
    }
    if (goal.kind === 'no-pawns' && !piecesOf(entry.fen, other(entry.sideToMove)).some((p) => p.type === 'p')) {
      problems.push('There is no pawn to catch.')
    }
    if (o.within !== undefined && (!Number.isInteger(o.within) || o.within < 1 || o.within > 40)) problems.push('The move allowance is not a sensible number.')
    unproved.push('Whether the position is won or drawn is not settled here; what is checked is that the job can be stated as a fact about the position and is not already done.')
  }

  // The authored defence: every reply has to be legal in the position it answers, and answer it for the right side.
  for (const written of entry.defence ?? []) {
    const ok = checkFen(written.fen)
    if (!ok.ok) { problems.push(`A defensive position is not legal: ${ok.reason ?? ''}`); continue }
    if (sideToMove(written.fen) === entry.sideToMove) problems.push(`A defensive reply is written for a position where it is the learner's move: ${written.fen}`)
    if (!applyMove(written.fen, written.play)) problems.push(`The defensive reply "${written.play}" cannot be played in ${written.fen}`)
    if (!written.why.trim()) problems.push(`The defensive reply "${written.play}" does not say why.`)
  }
  const keys = (entry.defence ?? []).map((d) => positionKey(d.fen))
  if (new Set(keys).size !== keys.length) problems.push('Two defensive replies answer the same position.')
  if (entry.defence?.length) proved.push(`${entry.defence.length} written ${entry.defence.length === 1 ? 'reply is' : 'replies are'} legal where they are written.`)

  // The model line: playable from the position, and it gets there.
  if (entry.line?.length) {
    const walk = walkLine(entry, entry.line)
    if (walk.failedAt !== undefined) {
      problems.push(`The line stops being legal at move ${walk.failedAt + 1} ("${entry.line[walk.failedAt]}").`)
    } else if (!walk.met) {
      problems.push('The line is legal but does not reach the objective, so it is not a model line.')
    } else {
      proved.push(`The written line is legal throughout and reaches the objective in ${walk.learnerMoves} of the learner's moves.`)
    }
  }

  return { id: entry.id, ok: problems.length === 0, problems, proved, unproved, nodes }
}

/** Plays a written line from the entry's position and says whether it is legal and whether it gets there. */
export function walkLine(entry: EndgameEntry, line: readonly string[]): { failedAt?: number; met: boolean; learnerMoves: number; fen: string } {
  let state = startDrill(entry)
  for (const [index, text] of line.entries()) {
    const made = applyMove(state.fen, text)
    if (!made) return { failedAt: index, met: false, learnerMoves: state.moves.filter((m) => m.by === 'learner').length, fen: state.fen }
    const by: 'learner' | 'defence' = sideToMove(state.fen) === entry.sideToMove ? 'learner' : 'defence'
    state = { ...state, fen: made.after, moves: [...state.moves, { san: made.san, uci: made.uci, fen: made.after, by }] }
  }
  const progress = progressOf(entry, state)
  return { met: objectiveMet(entry, state.fen, progress), learnerMoves: progress.learnerMoves, fen: state.fen }
}

export interface CatalogueCheck {
  entries: EntryCheck[]
  authored: number
  passed: number
  problems: string[]
}

/** The whole catalogue, checked, including the things that are only wrong between entries. */
export function verifyCatalogue(entries: readonly EndgameEntry[], options: VerifyOptions = {}): CatalogueCheck {
  const checks = entries.map((entry) => verifyEntry(entry, options))
  const problems: string[] = []
  const ids = entries.map((e) => e.id)
  for (const id of new Set(ids)) {
    if (ids.filter((other2) => other2 === id).length > 1) problems.push(`The id "${id}" is used more than once.`)
  }
  const fens = entries.map((e) => positionKey(e.fen))
  for (const key of new Set(fens)) {
    if (fens.filter((f) => f === key).length > 1) problems.push(`Two entries use the same position: ${key}`)
  }
  return { entries: checks, authored: entries.length, passed: checks.filter((c) => c.ok).length, problems }
}

/** How an entry's claim was settled, for the screen to say so without overstating it. */
export function proofKind(entry: EndgameEntry): 'searched' | 'checked' {
  const o = entry.objective
  if (o.kind === 'mate-in') return 'searched'
  if (o.kind === 'promote' && o.moves !== undefined) return 'searched'
  if (o.kind === 'draw' && o.forcedIn !== undefined) return 'searched'
  return 'checked'
}

export const PROOF_TEXT: Record<'searched' | 'checked', string> = {
  searched: 'Proved here: every defence was tried and the objective is forced in the number stated.',
  checked: 'Checked here: the position is legal, the objective is a fact about the position, and the written line reaches it. That the ending is won or drawn is standard theory, not something Orbis has proved.'
}
