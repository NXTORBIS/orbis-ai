import fsp from 'node:fs/promises';
import path from 'node:path';
import { ORBIS_NATIVE_TYPES, type ContentItem, type ContentProviderInfo } from '../../shared/integration/content-providers';
import type { Catalog } from '../store/Catalog';

/**
 * Registry of content providers for the unified library. Built-in providers
 * are backed by real local data. External providers (the Orbis app) can be
 * registered at runtime through the host integration; none is assumed.
 */

export interface ContentProvider {
  info(): ContentProviderInfo;
  list(limit: number): Promise<ContentItem[]>;
}

export class ContentRegistry {
  private providers = new Map<string, ContentProvider>();

  constructor(catalog: Catalog) {
    this.register(new DownloadsProvider(catalog));
    this.register(new GeneratedProvider(catalog));
    this.register(new ImportedProvider(catalog));
    this.register(new ProjectsProvider(catalog));
  }

  register(p: ContentProvider): void {
    this.providers.set(p.info().id, p);
  }

  has(id: string): boolean {
    return this.providers.has(id);
  }

  /** Find an item by provider and id (used to open native content safely). */
  async find(providerId: string, itemId: string): Promise<ContentItem | undefined> {
    return (await this.list(providerId, 100000)).find((i) => i.id === itemId);
  }

  unregister(id: string): void {
    this.providers.delete(id);
  }

  /** Every provider plus a placeholder entry for each native type nobody provides. */
  infos(): ContentProviderInfo[] {
    const infos = [...this.providers.values()].map((p) => p.info());
    const served = new Set(infos.flatMap((i) => i.types));
    const missing = ORBIS_NATIVE_TYPES.filter((t) => !served.has(t));
    if (missing.length) {
      infos.push({
        id: 'orbis-native',
        label: 'Orbis app content',
        types: [...missing],
        availability: 'not_connected',
        storage: 'none',
        actions: [],
        removalSemantics: 'Not applicable until the Orbis app provides this content.',
        note: 'Notes, flowcharts, mind maps, whiteboards, projects and other Orbis content appear here once the Orbis desktop app registers a provider. Nothing is simulated.',
        builtIn: false,
      });
    }
    return infos;
  }

  async list(providerId: string, limit = 500): Promise<ContentItem[]> {
    const p = this.providers.get(providerId);
    if (!p) return [];
    return p.list(limit);
  }
}

async function present(p: string): Promise<{ ok: boolean; size?: number; mtime?: number }> {
  try {
    const st = await fsp.stat(p);
    return { ok: true, size: st.size, mtime: st.mtimeMs };
  } catch {
    return { ok: false };
  }
}

class DownloadsProvider implements ContentProvider {
  constructor(private readonly catalog: Catalog) {}
  info(): ContentProviderInfo {
    return {
      id: 'downloads', label: 'Browser downloads', types: ['download'], availability: 'available', storage: 'filesystem', builtIn: true,
      actions: ['open', 'reveal', 'remove_reference', 'tag', 'collect'],
      removalSemantics: 'Removing an entry forgets where the download came from; the file stays on disk.',
      note: 'Entries are registered by the Orbis browser. Other browsers’ private histories are not read.',
    };
  }
  async list(limit: number): Promise<ContentItem[]> {
    const rows = (await this.catalog.downloads()).slice(0, limit);
    return rows.map((d) => ({ id: d.id, providerId: 'downloads', type: 'download', title: path.basename(d.path), path: d.path, modifiedMs: d.modifiedMs, size: d.size, source: d.url ?? undefined, present: !!d.exists }));
  }
}

class GeneratedProvider implements ContentProvider {
  constructor(private readonly catalog: Catalog) {}
  info(): ContentProviderInfo {
    return {
      id: 'generated', label: 'AI-generated files', types: ['generated_file'], availability: 'available', storage: 'filesystem', builtIn: true,
      actions: ['open', 'reveal', 'remove_reference', 'tag', 'collect'],
      removalSemantics: 'Removing an entry keeps the file; only its “generated by” record is forgotten.',
    };
  }
  async list(limit: number): Promise<ContentItem[]> {
    const rows = (await this.catalog.generated()).slice(0, limit);
    return Promise.all(rows.map(async (g) => {
      const st = await present(g.path);
      return { id: g.id, providerId: 'generated', type: 'generated_file', title: path.basename(g.path), path: g.path, modifiedMs: st.mtime, size: st.size, source: g.generator, present: st.ok };
    }));
  }
}

class ImportedProvider implements ContentProvider {
  constructor(private readonly catalog: Catalog) {}
  info(): ContentProviderInfo {
    return {
      id: 'imported', label: 'Imported copies', types: ['imported_file'], availability: 'available', storage: 'filesystem', builtIn: true,
      actions: ['open', 'reveal', 'tag', 'collect'],
      removalSemantics: 'Imported copies are ordinary files in the Orbis Library folder; delete them like any other file. The originals were never changed.',
    };
  }
  async list(limit: number): Promise<ContentItem[]> {
    return Promise.all(this.catalog.itemsBySource('import', limit).map(async (it) => {
      const st = await present(it.path);
      return { id: it.id, providerId: 'imported', type: 'imported_file', title: path.basename(it.path), path: it.path, modifiedMs: st.mtime, size: st.size, present: st.ok && !it.missing };
    }));
  }
}

class ProjectsProvider implements ContentProvider {
  constructor(private readonly catalog: Catalog) {}
  info(): ContentProviderInfo {
    return {
      id: 'projects', label: 'Projects', types: ['project'], availability: 'available', storage: 'filesystem', builtIn: true,
      actions: ['open', 'reveal'],
      removalSemantics: 'Removing a project forgets the project entry and its associations; the folder and files are untouched.',
      note: 'Folders recognised by project files, or added by you.',
    };
  }
  async list(limit: number): Promise<ContentItem[]> {
    return Promise.all(this.catalog.projects().slice(0, limit).map(async (p) => {
      const st = await present(p.root);
      return { id: p.id, providerId: 'projects', type: 'project', title: p.name, path: p.root, modifiedMs: st.mtime, source: p.kind, present: st.ok };
    }));
  }
}
