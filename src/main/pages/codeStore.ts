import { mkdir, rm, writeFile, readFile } from 'node:fs/promises'
import { join } from 'node:path'
import { dataDirFor } from '../../shared/profiles.ts'
import { isPageId } from '../../shared/pages/identity.ts'
import type { PageFile } from '../../shared/pages/codePage.ts'

/**
 * Where a code Page's files live, and how they get there.
 *
 * The specification route never needed this: a Page described as a specification is rendered from its document, so
 * nothing is ever written down. A Page written as code is files, and files need a place and rules about that place.
 *
 * Three rules, and each is a thing that would otherwise go wrong:
 *
 *   1. **Inside a profile.** A Page belongs to whoever made it, so it sits under that profile's folder and leaves
 *      with it when the profile is exported or deleted. A shared folder would mean one person's Page appearing in
 *      somebody else's library.
 *   2. **One folder per Page, named by its id.** The id is generated by Orbis and checked here anyway, because a
 *      folder name assembled from anything a model wrote is a path traversal waiting to be written.
 *   3. **Only the three names Orbis chose.** The files are produced by `filesFor`, which gives them fixed names; this
 *      refuses anything else rather than trusting that it always will.
 */

/** The only files a code Page may be made of. Fixed here as well as in `filesFor`, so neither can drift alone. */
const ALLOWED = new Set(['index.html', 'page.js', 'page.css'])

/**
 * A page id, as the rest of Pages defines one.
 *
 * Deliberately the same check rather than a looser local one. A folder name is assembled from this, so a wider rule
 * here would be the one place a path could be something the rest of Orbis would have refused.
 */
export const isSafePageId = (id: unknown): id is string => isPageId(id)

export interface CodeStoreOptions {
  userData: string
  profileId(): Promise<string>
}

export class CodeStore {
  private readonly o: CodeStoreOptions
  /** Where each Page was written, so serving it never has to guess which profile it belonged to. */
  private readonly roots = new Map<string, string>()

  constructor(options: CodeStoreOptions) {
    this.o = options
  }

  /** Where a Page's files would go for a given profile. The one place the path is assembled. */
  private pathFor(profileId: string, pageId: string): string {
    if (!isSafePageId(pageId)) throw new Error('That is not a page id.')
    return join(this.o.userData, dataDirFor(profileId), 'code-pages', pageId)
  }

  /**
   * The folder a Page is actually served from.
   *
   * The folder `write` created, remembered -- not one computed from whichever profile is active now. The host asks
   * for this synchronously while laying out a view, so it cannot look the profile up; and computing it from a cached
   * active profile would mean that switching profiles while a Page is open serves another profile's files under this
   * Page's id. Remembering what was written is the only version of this that cannot be wrong.
   */
  rootFor(pageId: string): string {
    const known = this.roots.get(pageId)
    if (known === undefined) throw new Error('That Page has not been written.')
    return known
  }

  /** Writes a Page's files, replacing whatever was there. Returns the folder they are in. */
  async write(pageId: string, files: readonly PageFile[]): Promise<string> {
    if (!isSafePageId(pageId)) throw new Error('That is not a page id.')
    for (const file of files) {
      // Checked rather than assumed: these names come from `filesFor` today, and a path from anywhere else is the
      // one mistake in this file that would matter.
      if (!ALLOWED.has(file.path)) throw new Error(`A Page may not have a file called "${file.path}".`)
    }

    const root = this.pathFor(await this.o.profileId(), pageId)
    /*
     * Cleared first, so a Page that lost a file does not keep serving the old one.
     *
     * A rewritten Page with a smaller set of files would otherwise be a mixture of two versions, which is the kind of
     * thing that works until it suddenly does not and cannot be reasoned about afterwards.
     */
    await rm(root, { recursive: true, force: true }).catch(() => undefined)
    await mkdir(root, { recursive: true })
    await Promise.all(files.map((file) => writeFile(join(root, file.path), file.content, 'utf8')))
    this.roots.set(pageId, root)
    return root
  }

  /** What a Page is made of now, for showing somebody the code that is running. Empty when there is no such Page. */
  async read(pageId: string): Promise<PageFile[]> {
    if (!isSafePageId(pageId)) return []
    const root = this.pathFor(await this.o.profileId(), pageId)
    const out: PageFile[] = []
    for (const path of ALLOWED) {
      const content = await readFile(join(root, path), 'utf8').catch(() => null)
      if (content !== null) out.push({ path, content })
    }
    return out
  }

  /** Removes a Page's files. Called when the Page is removed, so a deleted Page does not leave its code behind. */
  async forget(pageId: string): Promise<void> {
    if (!isSafePageId(pageId)) return
    await rm(this.pathFor(await this.o.profileId(), pageId), { recursive: true, force: true }).catch(() => undefined)
    this.roots.delete(pageId)
  }
}
