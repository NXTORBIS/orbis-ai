import { mkdir, readdir, readFile, rename, rm, stat, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { dataDirFor } from '../../shared/profiles.ts'
import { isArtifactId, isVersionId, readRecord, type ArtifactRecord } from '../../shared/artifacts/model.ts'

/**
 * Where artifacts live on disk, and how they get there.
 *
 * One folder per artifact, under the profile that made it:
 *
 *     <profile>/artifacts/<artifact id>/
 *       current/            the version that is current: the record, the source, the stored copy
 *       versions/<id>/      every earlier version, each with the same three files, never touched again
 *
 * Three rules, each the answer to a specific way this goes wrong:
 *
 *   1. **Inside a profile.** `dataDirFor` is imported, never re-derived -- a second derivation agrees with the first
 *      only until somebody changes one of them.
 *   2. **Every id is checked before any path is joined.** Artifact ids and version ids are generated by Orbis, and they
 *      are checked here anyway, because a folder name assembled from anything a caller sent is a path traversal
 *      waiting to be written.
 *   3. **Only names Orbis chose.** The three file names are fixed in this file; a caller passing any other is refused.
 *
 * Writes are staged. The new files go into `current.staging`; the current folder, if there is one, is renamed into
 * `versions/` under its own version id; then the staging folder is renamed to `current`. Every step is a rename, so
 * nothing is copied and a crash halfway leaves either the old current or the new one -- and the old version's files
 * are never deleted by a write, which is what "nothing is ever replaced" means on disk.
 *
 * An artifact written before versions existed has its files directly in its own folder. It is still read, from
 * there, and the first write that touches it moves it into the new shape.
 *
 * Two things follow from every step being a rename, and both are about Windows:
 *
 *   - **A rename is tried again when the folder is busy.** A file that has just been written is opened by whatever
 *     watches new files -- a virus scanner, the search index -- and for a moment the folder it is in cannot be
 *     renamed. That is not a failure of the write; it passes in milliseconds. So a refused rename waits and tries
 *     again, a few times, before it is reported.
 *   - **A read waits its turn.** Between the old folder moving away and the new one arriving there is no current
 *     folder at all. A read that landed in that gap would say the artifact does not exist, and a read that had a
 *     file open would be what stopped the rename. Reads go through the same queue as writes, so neither happens.
 */

export const RECORD_FILE = 'artifact.json'
export const SOURCE_FILE = 'source.json'
/** The stored copy is `content` plus the format's extension, so this is a prefix rather than a name. */
export const CONTENT_PREFIX = 'content'

const CURRENT = 'current'
const VERSIONS = 'versions'
const STAGING = 'current.staging'

export interface StoredFile {
  name: string
  bytes: Uint8Array
}

export interface ArtifactStoreOptions {
  userData: string
  /** Moves a file or folder. The file system's own, unless a test needs one that refuses. */
  rename?(from: string, to: string): Promise<void>
  /** Waits. Real time, unless a test would rather not. */
  wait?(ms: number): Promise<void>
}

/** What Windows says when something else has the file open for a moment. Worth waiting for; nothing else is. */
const BUSY: ReadonlySet<string> = new Set(['EPERM', 'EBUSY', 'EACCES', 'ENOTEMPTY'])
/** How long to wait before each further try. About two seconds in all: longer than any scanner holds a small file. */
const RETRY_AFTER_MS: readonly number[] = Object.freeze([15, 30, 60, 120, 240, 480, 960])

export class ArtifactStore {
  private readonly o: ArtifactStoreOptions
  /** One chain per artifact, so two writes to the same artifact land in order and never interleave. */
  private readonly queues = new Map<string, Promise<unknown>>()

  constructor(options: ArtifactStoreOptions) {
    this.o = options
  }

  private rootFor(profileId: string): string {
    return join(this.o.userData, dataDirFor(profileId), 'artifacts')
  }

  /** The folder an artifact lives in. The one place the path is assembled, and it refuses before it joins. */
  private pathFor(profileId: string, artifactId: string): string {
    if (!isArtifactId(artifactId)) throw new Error('That is not an artifact id.')
    return join(this.rootFor(profileId), artifactId)
  }

  /** A rename that waits out a folder being busy. Any other refusal, and a busy that does not pass, is thrown. */
  private async move(from: string, to: string): Promise<void> {
    const once = this.o.rename ?? rename
    const wait = this.o.wait ?? ((ms: number) => new Promise<void>((resolve) => setTimeout(resolve, ms)))
    for (let attempt = 0; ; attempt++) {
      try {
        await once(from, to)
        return
      } catch (err) {
        const code = (err as NodeJS.ErrnoException | null)?.code ?? ''
        if (!BUSY.has(code) || attempt >= RETRY_AFTER_MS.length) throw err
        await wait(RETRY_AFTER_MS[attempt])
      }
    }
  }

  private queued<T>(path: string, work: () => Promise<T>): Promise<T> {
    const previous = this.queues.get(path) ?? Promise.resolve()
    const next = previous.then(work, work)
    // The queue remembers only that the last piece of work has finished -- never what it handed back, which for a
    // read is the whole file -- and lets go of an artifact as soon as nothing is waiting on it.
    const tail = next.then(
      () => undefined,
      () => undefined
    )
    this.queues.set(path, tail)
    void tail.then(() => {
      if (this.queues.get(path) === tail) this.queues.delete(path)
    })
    return next
  }

  private static allowed(name: string): boolean {
    return name === RECORD_FILE || name === SOURCE_FILE || /^content\.[a-z0-9]{1,8}$/.test(name)
  }

  private static async exists(path: string): Promise<boolean> {
    try {
      await stat(path)
      return true
    } catch {
      return false
    }
  }

  /** Where the current files are: the `current` folder, or the artifact's own folder for one written before versions. */
  private async currentDir(root: string): Promise<string | null> {
    if (await ArtifactStore.exists(join(root, CURRENT, RECORD_FILE))) return join(root, CURRENT)
    if (await ArtifactStore.exists(join(root, RECORD_FILE))) return root
    return null
  }

  /**
   * An artifact's files, written as one unit, with what was current before kept as a version.
   *
   * Every step is a rename. The old current goes under `versions/<its version id>` -- its files move, they are not
   * copied and not deleted -- and only then does the staging folder become current. If that last rename fails, the
   * old current is put back, so a failed write leaves what was there.
   */
  async write(profileId: string, record: ArtifactRecord, files: readonly StoredFile[]): Promise<string> {
    const root = this.pathFor(profileId, record.artifactId)
    if (!isVersionId(record.versionId)) throw new Error('That is not a version id.')
    for (const file of files) {
      if (!ArtifactStore.allowed(file.name)) throw new Error(`An artifact may not have a file called "${file.name}".`)
    }
    return this.queued(root, async () => {
      const staging = join(root, STAGING)
      const current = join(root, CURRENT)
      await rm(staging, { recursive: true, force: true }).catch(() => undefined)
      await mkdir(staging, { recursive: true })
      await writeFile(join(staging, RECORD_FILE), JSON.stringify(record), { encoding: 'utf8', mode: 0o600 })
      await Promise.all(files.map((file) => writeFile(join(staging, file.name), file.bytes, { mode: 0o600 })))

      // What is current now, if anything, and the version id it goes under.
      const was = await this.currentDir(root)
      let kept: string | null = null
      if (was !== null) {
        const previous = readRecord(JSON.parse(await readFile(join(was, RECORD_FILE), 'utf8')).valueOf())
        if (previous !== null) {
          kept = join(root, VERSIONS, previous.versionId)
          await mkdir(join(root, VERSIONS), { recursive: true })
          await rm(kept, { recursive: true, force: true }).catch(() => undefined)
          if (was === current) {
            await this.move(current, kept)
          } else {
            // The old shape: files in the artifact's own folder. Moved one by one into their version folder.
            await mkdir(kept, { recursive: true })
            for (const name of await readdir(was)) {
              if (ArtifactStore.allowed(name)) await this.move(join(was, name), join(kept, name))
            }
          }
        }
      }
      try {
        await this.move(staging, current)
      } catch (err) {
        // Put the old current back before reporting, so a failed write leaves what was there.
        if (kept !== null && !(await ArtifactStore.exists(current))) await this.move(kept, current).catch(() => undefined)
        throw err
      }
      return current
    })
  }

  /**
   * A current version thrown away and the one before it made current again.
   *
   * For the moment a new version has been written and then failed its read-back: the artifact must not be left
   * pointing at a copy that does not check, and it must not be removed either, because the version before it was
   * fine. The failed folder is deleted; the previous one is renamed back. Both are renames or removals of whole
   * folders, so a crash between them leaves one of the two states and never a mixture.
   */
  async discardCurrent(profileId: string, artifactId: string, previousVersionId: string): Promise<boolean> {
    const root = this.pathFor(profileId, artifactId)
    if (!isVersionId(previousVersionId)) return false
    return this.queued(root, async () => {
      const current = join(root, CURRENT)
      const previous = join(root, VERSIONS, previousVersionId)
      if (!(await ArtifactStore.exists(join(previous, RECORD_FILE)))) return false
      await rm(current, { recursive: true, force: true, maxRetries: 5, retryDelay: 60 })
      await this.move(previous, current)
      return true
    })
  }

  /**
   * The record alone, replaced in place.
   *
   * For the moment after the files have been read back and checked, when the record gains its verification, and for
   * a rename. Written to a sibling and renamed over, so a crash between the two leaves the old record rather than
   * half of the new one.
   */
  async writeRecord(profileId: string, record: ArtifactRecord): Promise<void> {
    const root = this.pathFor(profileId, record.artifactId)
    await this.queued(root, async () => {
      const dir = (await this.currentDir(root)) ?? join(root, CURRENT)
      await mkdir(dir, { recursive: true })
      const path = join(dir, RECORD_FILE)
      await writeFile(`${path}.tmp`, JSON.stringify(record), { encoding: 'utf8', mode: 0o600 })
      await this.move(`${path}.tmp`, path)
    })
  }

  /** The record, or null when there is none or it is damaged. A damaged record is refused, not repaired. */
  async readRecord(profileId: string, artifactId: string): Promise<ArtifactRecord | null> {
    if (!isArtifactId(artifactId)) return null
    const root = this.pathFor(profileId, artifactId)
    return this.queued(root, async () => {
      try {
        const dir = await this.currentDir(root)
        if (dir === null) return null
        return readRecord(JSON.parse(await readFile(join(dir, RECORD_FILE), 'utf8')))
      } catch {
        return null
      }
    })
  }

  /** One of the current version's files, or null. Only the fixed names can be asked for. */
  async readFile(profileId: string, artifactId: string, name: string): Promise<Uint8Array | null> {
    if (!isArtifactId(artifactId) || !ArtifactStore.allowed(name)) return null
    const root = this.pathFor(profileId, artifactId)
    return this.queued(root, async () => {
      try {
        const dir = await this.currentDir(root)
        if (dir === null) return null
        return new Uint8Array(await readFile(join(dir, name)))
      } catch {
        return null
      }
    })
  }

  /** One of an earlier version's files, or null. Both ids are checked before the path is made. */
  async readVersionFile(profileId: string, artifactId: string, versionId: string, name: string): Promise<Uint8Array | null> {
    if (!isArtifactId(artifactId) || !isVersionId(versionId) || !ArtifactStore.allowed(name)) return null
    const root = this.pathFor(profileId, artifactId)
    return this.queued(root, async () => {
      try {
        return new Uint8Array(await readFile(join(root, VERSIONS, versionId, name)))
      } catch {
        return null
      }
    })
  }

  /** Every readable record in a profile, newest first. A folder with a damaged record is skipped, not listed. */
  async list(profileId: string): Promise<ArtifactRecord[]> {
    let names: string[]
    try {
      names = await readdir(this.rootFor(profileId))
    } catch {
      return []
    }
    const records = await Promise.all(names.filter(isArtifactId).map((id) => this.readRecord(profileId, id)))
    return records.filter((one): one is ArtifactRecord => one !== null).sort((a, b) => b.updatedAt - a.updatedAt)
  }

  /** Removes an artifact and everything in its folder: every version with it. */
  async remove(profileId: string, artifactId: string): Promise<boolean> {
    if (!isArtifactId(artifactId)) return false
    const root = this.pathFor(profileId, artifactId)
    return this.queued(root, async () => {
      await rm(root, { recursive: true, force: true, maxRetries: 5, retryDelay: 60 })
      return true
    })
  }
}
