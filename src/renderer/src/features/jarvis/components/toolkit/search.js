const STOP = new Set(['a', 'an', 'the', 'of', 'for', 'to', 'my', 'in', 'on', 'and', 'with', 'from', 'how', 'much', 'do', 'i', 'is', 'me', 'need', 'want', 'can', 'best', 'good', 'use', 'using', 'it', 'that', 'at', 'by']);

export const normalise = (text) => String(text).toLowerCase().replace(/[^a-z0-9\s/+#.-]/g, ' ').replace(/\s+/g, ' ').trim();

const textCache = new Map();
const haystackFor = (tool, categoryLabel) => {
  if (!textCache.has(tool.id)) {
    textCache.set(tool.id, normalise([tool.label, tool.desc, tool.id.replace(/-/g, ' '), categoryLabel].join(' ')));
  }
  return textCache.get(tool.id);
};

const intentIds = (query) => {
  const found = new Set();
  Object.entries(INTENTS).forEach(([phrase, ids]) => {
    if (query === phrase || query.includes(phrase)) ids.forEach((id) => found.add(id));
  });
  return found;
};

const scoreTool = (tool, categoryLabel, tokens, query, intents) => {
  const haystack = haystackFor(tool, categoryLabel);
  const label = normalise(tool.label);
  const labelWords = label.split(' ');
  let score = 0;

  if (tool.id === query || label === query) score += 200;
  if (query.length > 2 && label.includes(query)) score += 120;
  if (intents.has(tool.id)) score += 90;
  if (!score && query.length > 3 && haystack.includes(query)) score += 45;

  let missing = 0;
  tokens.forEach((token) => {
    const forms = [token, ...(WORDS[token] || [])];
    if (!forms.some((form) => haystack.includes(form))) {
      missing += 1;
      return;
    }
    const onLabel = forms.some((form) => labelWords.some((word) => word.startsWith(form)));
    score += onLabel ? 16 : 7;
  });

  if (!tokens.length) return score;
  if (missing === tokens.length) return 0;
  if (missing > 0 && score < 60) return 0;
  return score - missing * 4;
};

/** Ranked matches, best first. Empty query returns an empty list. */
export function searchTools(categories, query) {
  const clean = normalise(query);
  if (!clean) return [];
  const tokens = clean.split(' ').filter((token) => token && !STOP.has(token));
  const intents = intentIds(clean);

  const hits = [];
  categories.forEach((category) => {
    category.tools.forEach((tool) => {
      const score = scoreTool(tool, category.label, tokens.length ? tokens : [clean], clean, intents);
      if (score > 0) hits.push({ tool, category, score });
    });
  });

  return hits
    .sort((a, b) => b.score - a.score || a.tool.label.length - b.tool.label.length)
    .slice(0, 60);
}