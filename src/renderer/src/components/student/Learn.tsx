import { useCallback, useEffect, useState } from 'react'
import { Check, HelpCircle, Mic, Plus, RotateCcw, Sparkles } from 'lucide-react'
import { Segmented } from '../../ui'
import TeachBack from './TeachBack'
import { onDay, type Call } from './useStudent'
import type { LearningItem, LearningReview, Mistake, StudentSnapshot } from '../../../../shared/student/types'
import type { NoticeKind } from '../../lib/notices'

/**
 * Orbis Learn: a little every day, and whatever is due to come back.
 *
 * Three things on one page, in the order they matter: what is due, today's new things, and what keeps going wrong.
 * Review comes first because something half-remembered is worth more attention than something new, and a student who
 * only ever meets new material forgets all of it.
 *
 * Every card says where its content came from. Bundled content is labelled "Orbis Learning" and anything Orion wrote
 * says so -- a student reading a generated explanation should know that is what they are reading.
 */

const LABELS: Record<string, string> = {
  word: 'Word',
  concept: 'Concept',
  fact: 'Fact',
  teaser: 'Puzzle',
  quiz: 'Quiz',
  flashcard: 'Card',
  science: 'Science',
  maths: 'Maths',
  history: 'History',
  vocabulary: 'Vocabulary'
}

const ORIGINS: Record<string, string> = { orbis: 'Orbis Learning', orion: 'Generated by Orion', web: 'Web resource', student: 'Yours' }

function Card({ item, onAnswer, answered }: { item: LearningItem; onAnswer(answer: 'known' | 'unsure' | 'forgot', correct?: boolean, given?: string): void; answered: boolean }): React.JSX.Element {
  const [shown, setShown] = useState(false)
  const [given, setGiven] = useState('')
  const body = item.body

  return (
    <article className="st-card">
      <header>
        <span className="st-card-kind">{LABELS[item.kind] ?? item.kind}</span>
        {item.subject ? <span className="st-faint">{item.subject}</span> : null}
        <span className="st-origin">{ORIGINS[item.origin] ?? item.origin}</span>
      </header>
      <h4>{item.title}</h4>
      {body.pronunciation ? (
        <p className="st-faint">
          {body.pronunciation} · {body.partOfSpeech}
        </p>
      ) : null}
      {body.definition ? <p>{body.definition}</p> : null}
      {body.keyIdea ? (
        <p>
          <strong>Key idea:</strong> {body.keyIdea}
        </p>
      ) : null}
      {body.text ? <p>{body.text}</p> : null}
      {body.example ? (
        <p className="st-example">
          <em>{body.example}</em>
        </p>
      ) : null}
      {body.synonyms && body.synonyms.length > 0 ? (
        <p className="st-faint">
          Similar: {body.synonyms.join(', ')}
          {body.antonyms && body.antonyms.length > 0 ? ` · Opposite: ${body.antonyms.join(', ')}` : ''}
        </p>
      ) : null}
      {body.commonMistake ? (
        <p className="st-warnline">
          <strong>Watch out:</strong> {body.commonMistake}
        </p>
      ) : null}
      {body.source ? <p className="st-faint small">Source: {body.source}</p> : null}

      {body.question ? (
        <div className="st-quiz">
          <p>
            <strong>{body.question}</strong>
          </p>
          {!shown ? (
            <>
              <input value={given} onChange={(e) => setGiven(e.target.value.slice(0, 300))} placeholder="Your answer" aria-label="Your answer" />
              <button type="button" className="st-btn" onClick={() => setShown(true)}>
                Show the answer
              </button>
            </>
          ) : (
            <>
              <p className="st-answer">{body.answer}</p>
              {!answered ? (
                <div className="st-card-actions">
                  {/* Whether it was right is the student's own call: nothing here tries to mark free text. */}
                  <button type="button" className="st-btn primary" onClick={() => onAnswer('known', true, given)}>
                    <Check size={14} aria-hidden /> I had it
                  </button>
                  <button type="button" className="st-btn" onClick={() => onAnswer('unsure', false, given)}>
                    Nearly
                  </button>
                  <button type="button" className="st-btn" onClick={() => onAnswer('forgot', false, given)}>
                    <RotateCcw size={14} aria-hidden /> Not yet
                  </button>
                </div>
              ) : (
                <p className="st-faint">Saved. It will come back round.</p>
              )}
            </>
          )}
        </div>
      ) : !answered ? (
        <div className="st-card-actions">
          <button type="button" className="st-btn primary" onClick={() => onAnswer('known')}>
            <Check size={14} aria-hidden /> Got it
          </button>
          <button type="button" className="st-btn" onClick={() => onAnswer('unsure')}>
            Show me again
          </button>
        </div>
      ) : (
        <p className="st-faint">Saved.</p>
      )}
    </article>
  )
}

export default function Learn({
  snapshot,
  call,
  onNotify,
  onOpenOrion
}: {
  snapshot: StudentSnapshot
  call: Call
  onNotify(message: string, kind?: NoticeKind): void
  onOpenOrion?(prompt: string): void
}): React.JSX.Element {
  const [today, setToday] = useState<{ word: LearningItem | null; mix: LearningItem[]; due: number; dueItems: { item: LearningItem; review: LearningReview }[] } | null>(null)
  const [mistakes, setMistakes] = useState<Mistake[]>([])
  const [answered, setAnswered] = useState<Set<string>>(new Set())
  const [tab, setTab] = useState<'today' | 'review' | 'mistakes' | 'mixups'>('today')
  /**
   * The things somebody keeps mixing up.
   *
   * A pair of ideas that swap places in your head is a different problem from one you have not learned -- more
   * practice on each one separately does nothing for it. Writing down which two, and what actually tells them
   * apart, is the thing that works, so Orbis keeps them and shows them back rather than quietly filing them.
   */
  const [mixups, setMixups] = useState<{ id: string; concept: string; subject: string | null; note: string; at: number; resolvedAt: number | null }[]>([])
  const [writingMixup, setWritingMixup] = useState<{ id?: string; concept: string; note: string; subject: string } | null>(null)
  /**
   * The mistake being explained back, if any.
   *
   * Explaining a mistake back from memory is the strongest thing somebody can do with their mistake book, and the
   * only way to find out whether it has actually stuck. Orbis does not mark it -- it shows their own note back
   * afterwards and they tick what they covered.
   */
  const [explaining, setExplaining] = useState<{ ask: string; answer: string; source: 'mistake'; conceptId: string | null } | null>(null)
  /** Written help, offered only when Orion is set up. */
  const [canGenerate, setCanGenerate] = useState(false)
  const [whyItHappens, setWhyItHappens] = useState<{ concept: string; text: string } | null>(null)

  const load = useCallback(async (): Promise<void> => {
    const [one, two, three] = await Promise.all([
      call<typeof today>('today-learning'),
      call<Mistake[]>('mistakes-to-review'),
      call<typeof mixups>('confusions')
    ])
    setToday(one ?? null)
    setMistakes(Array.isArray(two) ? two : [])
    setMixups(Array.isArray(three) ? three : [])
  }, [call])

  useEffect(() => {
    void load()
  }, [load])

  useEffect(() => {
    void call<{ ok: boolean }>('can-generate').then((out) => setCanGenerate(out?.ok === true))
  }, [call])

  useEffect(() => {
    // Review first when there is anything due: that is the thing with a deadline.
    if ((today?.due ?? 0) > 0) setTab('review')
  }, [today?.due])

  const answer = async (item: LearningItem, how: 'known' | 'unsure' | 'forgot', correct?: boolean, given?: string): Promise<void> => {
    const out = await call<{ ok: boolean; xp: number }>('answer', item.id, how, correct === undefined ? {} : { correct, given })
    setAnswered((held) => new Set([...held, item.id]))
    if (out?.ok && out.xp > 0) onNotify(`+${out.xp} XP`)
    if (out?.ok) void load()
  }

  const due = today?.dueItems ?? []
  /** Mix-ups still open: the count beside the tab, as it was. */
  const openMixups = mixups.filter((one) => !one.resolvedAt).length

  return (
    <div className="st-learn" data-tour="learn-ask">
      <header className="st-section-head">
        <div>
          <h2>Learn</h2>
          <p className="st-faint">
            {snapshot.streaks.find((one) => one.kind === 'learning')?.current ?? 0} days of learning · {today?.due ?? 0} due
          </p>
        </div>
        {/* These four were each saying `aria-pressed`, so anything not looking at the screen heard four separate
            on/off switches rather than one choice of four — and nothing moved between them with the arrow keys.
            Same classes, same four words, same counts; only what the row says about itself has changed. */}
        <Segmented<'today' | 'review' | 'mistakes' | 'mixups'>
          className="st-tabs"
          optionClass="st-tab"
          label="What to work on"
          value={tab}
          options={[
            { value: 'review', label: `Review${today?.due ? ` (${today.due})` : ''}` },
            { value: 'today', label: 'Today' },
            { value: 'mistakes', label: `Mistakes${mistakes.length ? ` (${mistakes.length})` : ''}` },
            { value: 'mixups', label: `Mix-ups${openMixups ? ` (${openMixups})` : ''}` }
          ]}
          onChange={(one) => setTab(one)}
        />
      </header>

      {tab === 'review' ? (
        due.length === 0 ? (
          <p className="view-empty">You&apos;re caught up. Nothing is due to come back round.</p>
        ) : (
          <div className="st-cards">
            {due.map(({ item, review }) => (
              <div key={item.id}>
                <p className="st-faint small">
                  Last seen {onDay(review.lastSeenAt)} · seen {review.reviews} {review.reviews === 1 ? 'time' : 'times'}
                  {review.state === 'struggling' ? ' · this one keeps slipping' : ''}
                </p>
                <Card item={item} answered={answered.has(item.id)} onAnswer={(how, correct, given) => void answer(item, how, correct, given)} />
              </div>
            ))}
          </div>
        )
      ) : null}

      {tab === 'today' ? (
        <div className="st-cards">
          {today?.word ? <Card item={today.word} answered={answered.has(today.word.id)} onAnswer={(how, correct, given) => void answer(today.word as LearningItem, how, correct, given)} /> : null}
          {(today?.mix ?? []).map((item) => (
            <Card key={item.id} item={item} answered={answered.has(item.id)} onAnswer={(how, correct, given) => void answer(item, how, correct, given)} />
          ))}
          {!today?.word && (today?.mix.length ?? 0) === 0 ? <p className="view-empty">Nothing new for today. Everything Orbis has is already in your review.</p> : null}
        </div>
      ) : null}

      {tab === 'mixups' ? (
        <>
          <div className="st-row-actions">
            <button type="button" className="st-btn primary" onClick={() => setWritingMixup({ concept: '', note: '', subject: '' })}>
              <Plus size={15} aria-hidden /> Two things I mix up
            </button>
          </div>
          {mixups.length === 0 ? (
            <p className="view-empty">
              Nothing written down. When two ideas keep swapping places in your head, write both of them here with
              whatever tells them apart — that is the thing that fixes it, not more practice on each one.
            </p>
          ) : (
            <ul className="st-mistakes">
              {mixups.map((one) => (
                <li key={one.id} className={one.resolvedAt ? 'done' : ''}>
                  <div>
                    <strong>{one.concept}</strong>
                    <span className="st-faint">
                      {one.subject ? `${one.subject} · ` : ''}
                      {onDay(one.at)}
                      {one.resolvedAt ? ' · sorted out' : ''}
                    </span>
                    {one.note ? <p>{one.note}</p> : null}
                  </div>
                  <div className="st-mistake-actions">
                    {onOpenOrion ? (
                      <button
                        type="button"
                        className="st-btn"
                        onClick={() =>
                          onOpenOrion(
                            `I keep mixing up ${one.concept}${one.subject ? ` in ${one.subject}` : ''}. ${one.note || ''} Give me one clear way to tell them apart, then one question that only works if I can.`
                          )
                        }
                      >
                        <Sparkles size={14} aria-hidden /> Tell them apart
                      </button>
                    ) : null}
                    <button
                      type="button"
                      className="st-btn"
                      onClick={() => setWritingMixup({ id: one.id, concept: one.concept, note: one.note, subject: one.subject ?? '' })}
                    >
                      Edit
                    </button>
                    <button
                      type="button"
                      className="st-btn quiet"
                      onClick={() => {
                        void call('save-confusion', { ...one, resolvedAt: one.resolvedAt ? null : Date.now() }).then(() => void load())
                      }}
                    >
                      <Check size={14} aria-hidden /> {one.resolvedAt ? 'Still mixing them up' : 'Sorted now'}
                    </button>
                  </div>
                </li>
              ))}
            </ul>
          )}
        </>
      ) : null}

      {writingMixup ? (
        <div className="st-sheet" role="dialog" aria-modal="true" aria-label="Two things you mix up">
          <div className="st-sheet-card tight">
            <h3>Two things you mix up</h3>
            <label className="st-field">
              <span>Which two?</span>
              <input
                value={writingMixup.concept}
                onChange={(e) => setWritingMixup({ ...writingMixup, concept: e.target.value.slice(0, 200) })}
                placeholder="Speed and velocity"
                aria-label="Which two things"
              />
            </label>
            <label className="st-field">
              <span>What tells them apart? (if you know yet)</span>
              <textarea
                rows={4}
                value={writingMixup.note}
                onChange={(e) => setWritingMixup({ ...writingMixup, note: e.target.value.slice(0, 1000) })}
                aria-label="What tells them apart"
              />
            </label>
            <label className="st-field">
              <span>Subject</span>
              <input
                value={writingMixup.subject}
                onChange={(e) => setWritingMixup({ ...writingMixup, subject: e.target.value.slice(0, 80) })}
                aria-label="Subject"
              />
            </label>
            <div className="st-sheet-foot">
              <button
                type="button"
                className="st-btn primary"
                onClick={() => {
                  if (!writingMixup.concept.trim()) {
                    onNotify('Which two things?', 'warn')
                    return
                  }
                  void call('save-confusion', {
                    ...(writingMixup.id ? { id: writingMixup.id } : {}),
                    concept: writingMixup.concept.trim(),
                    note: writingMixup.note.trim(),
                    subject: writingMixup.subject.trim() || null
                  }).then(() => {
                    setWritingMixup(null)
                    void load()
                  })
                }}
              >
                Save
              </button>
              <button type="button" className="st-btn quiet" onClick={() => setWritingMixup(null)}>
                Cancel
              </button>
            </div>
          </div>
        </div>
      ) : null}

      {tab === 'mistakes' ? (
        mistakes.length === 0 ? (
          <p className="view-empty">No mistakes written down. You can add one from a session when something goes wrong.</p>
        ) : (
          <ul className="st-mistakes">
            {mistakes.map((one) => (
              <li key={one.id}>
                <div>
                  <strong>{one.concept}</strong>
                  <span className="st-faint">
                    {one.subject ? `${one.subject} · ` : ''}
                    {one.kind} · {onDay(one.at)}
                  </span>
                  {one.detail ? <p>{one.detail}</p> : null}
                </div>
                <div className="st-mistake-actions">
                  {onOpenOrion ? (
                    <button type="button" className="st-btn" onClick={() => onOpenOrion(`Explain ${one.concept}${one.subject ? ` in ${one.subject}` : ''} simply, then give me one example and one question to try. I got it wrong before: ${one.detail || 'no detail'}.`)}>
                      <Sparkles size={14} aria-hidden /> Explain it
                    </button>
                  ) : null}
                  {one.detail ? (
                    <button
                      type="button"
                      className="st-btn"
                      onClick={() => setExplaining({ ask: one.concept, answer: one.detail, source: 'mistake', conceptId: null })}
                    >
                      <Mic size={14} aria-hidden /> Explain it back
                    </button>
                  ) : null}
                  {canGenerate ? (
                    <button
                      type="button"
                      className="st-btn"
                      onClick={() =>
                        void call<{ ok: boolean; text?: string; why?: string }>('explain-mistake', one.id).then((out) => {
                          if (out?.ok && out.text) setWhyItHappens({ concept: one.concept, text: out.text })
                          else onNotify(out?.why ?? 'Nothing came back.', 'warn')
                        })
                      }
                    >
                      <HelpCircle size={14} aria-hidden /> Why does this happen?
                    </button>
                  ) : null}
                  <button
                    type="button"
                    className="st-btn quiet"
                    onClick={() => {
                      void call('save-mistake', { ...one, reviewedAt: Date.now() }).then(() => void load())
                    }}
                  >
                    <Check size={14} aria-hidden /> Reviewed
                  </button>
                </div>
              </li>
            ))}
          </ul>
        )
      ) : null}

      <p className="st-faint small foot">
        <HelpCircle size={12} aria-hidden /> What you have seen and answered stays on this computer, in this profile. You can clear it in Student Settings.
      </p>

      {whyItHappens ? (
        <div className="st-sheet" role="dialog" aria-modal="true" aria-label={`Why ${whyItHappens.concept} goes wrong`}>
          <div className="st-sheet-card">
            <header className="st-challenge-head">
              <div>
                <h3>{whyItHappens.concept}</h3>
                {/* A suggestion about the mistake, never a diagnosis of the student. */}
                <p className="st-faint small">Written by Orion, about the mistake — not about you</p>
              </div>
              <button type="button" className="st-icon" aria-label="Close" onClick={() => setWhyItHappens(null)}>
                ×
              </button>
            </header>
            <p className="st-explained">{whyItHappens.text}</p>
            <div className="st-sheet-foot">
              <button type="button" className="st-btn primary" onClick={() => setWhyItHappens(null)}>
                Done
              </button>
            </div>
          </div>
        </div>
      ) : null}

      {explaining ? (
        <TeachBack
          question={explaining}
          call={call}
          onNotify={(message: string, kind?: 'info' | 'warn') => onNotify(message, kind)}
          onClose={() => {
            setExplaining(null)
            void load()
          }}
        />
      ) : null}
    </div>
  )
}
